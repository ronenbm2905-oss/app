//
// ============================================================================
// 1.10.2026 — עוגן הזהות של הנהג עבר ממייל ל**נייד**
// ============================================================================
// המודל הקודם נשען על `token.email` + `token.email_verified`, והוא היה תקין:
// 328 בדיקות כללים, חמישה תנאי תביעה, ובידוד לפי uid. ובכל זאת **אף נהג לא
// נקשר** — `portalStatus` של כל 27 הנהגים נשאר `none`. הסיבה אינה באג: אין
// לחברה חשבונות Google ארגוניים, ולכן הכניסה דרשה גימייל **פרטי**, ואף עובד
// לא נתן אותו. מסלול שאיש אינו עובר בו אינו מסלול.
//
// הנייד כבר יושב בכרטיס הנהג. העובד מקליד מספר, מקבל SMS, מקיש קוד — וזהו.
//
// ⚠️ **החלפה, לא הוספה.** מסלול המייל הוסר כאן במלואו ולא נשמר במקביל. אפס
// נהגים מקושרים → אין מה להגר ואין את מי לשבור, ו-dual-anchor היה מכפיל את
// משטח ה-rules (שני סעיפי read, שני סעיפי claim) בלי להוסיף נהג אחד. זו
// ההעדפה המפורשת של עדי.
//
// ⚠️ **האדמינים לא נגעו.** `org.adminEmails` מול `token.email` +
// `email_verified`, כניסת Google, ו-`admins.js`/`canonEmail` כפי שהם. שם
// הסיכון מידתי (שני אנשים מוכרים), ושם המייל הוא כן מזהה זמין. שתי
// אוכלוסיות, שני עוגנים, שני נתיבי כללים נפרדים.
//
// ============================================================================
// מה **לא** השתנה, ולמה זה העיקר
// ============================================================================
// דרישת F1 של עדי נשארת בתוקפה במלואה: **הבידוד של הנהג לפי `uid` בלבד.**
// כל סעיף קריאה ב-firestore.rules נשען על `drivers/{id}.userId ==
// request.auth.uid`, ולא על טלפון. הנייד משמש **אך ורק לאירוע הקישור
// החד-פעמי**: האדמין מקליד את המספר בכרטיס הנהג, בעל המספר מאמת SMS, וה-uid
// שלו נצרב ברשומה. מרגע זה המספר אינו משתתף בשום החלטת הרשאה.
//
// ============================================================================
// ⚠️ ולמה הנייד הוא עוגן **חזק יותר** מהמייל, לא חלש יותר
// ============================================================================
// ב-Firebase Auth אין "טלפון לא מאומת". `token.phone_number` קיים בטוקן
// **רק** אם קוד ה-SMS אומת בפועל — אין מסלול שבו נרשמים עם מספר של מישהו
// אחר, בניגוד למייל (שם `email_verified` הוא תנאי שחייבים לזכור לבדוק, ובלעדיו
// כל אחד נרשם עם הכתובת של כל אחד). כלומר התנאי הראשון מבין החמישה עבר
// מ"בדיקה שאנחנו עושים" ל"תכונה של הספק" — ובכל זאת השארנו אותו מפורש
// (`tokenPhone() != ''`), כי כלל שמסתמך על הנחה שאינה כתובה הוא כלל שישבר
// בשקט ביום שהספק ישתנה.
//
// ⚠️ מה שכן נוסף: ה-SMS region policy בפרויקט נעולה ל**ישראל בלבד**, כדי
// שמספר זר לא יהפוך את מסלול הכניסה למשאבה של הודעות בתשלום.
//
// ============================================================================
// ⛔ ובמה הנייד **חלש יותר**, וזו הנקודה המסוכנת ביותר בקובץ הזה
// ============================================================================
// (עדי, סקירת 1.10.2026 §2.1 — חוסם)
//
// **ייחודיות המספר אינה בקרת rules. היא אינוריאנט נתונים.**
//
// `isSelfLinkClaim` בודק את הזהות **מול המסמך הספציפי** שמנסים לכתוב אליו,
// ו**ב-rules אין שאילתות**: הכלל אינו יכול לדעת שעוד רשומה נושאת את אותו
// מספר. ולכן אם שלוש רשומות נושאות את אותו מספר, מחזיק ה-SIM יכול לתבוע
// **כל אחת מהשלוש — לבחירתו, ובהצלחה**, כי כל אחת מהן מספקת את התנאי.
// זו אינה חסימת כניסה; זו דרך לראות את הרכב, הקנסות וההיסטוריה של עובד אחר,
// והיא עוברת את ה-rules דווקא **כי** הם כתובים נכון.
//
// בגרסת המייל זה נמנע בפועל רק בגלל `validateDriverLinkEmail` — חסימה
// **בלקוח**. לכן אותה שכבה בדיוק חייבת להתקיים לטלפון, בשלוש נקודות:
//   1. `validateDriverLinkPhone` — חוסם שמירה בטופס (למטה);
//   2. `phoneCollisions` — אסרשן ב-`npm run smoke`, שתופס את **הייבוא הבא**
//      ולא רק את הנתונים של היום;
//   3. חסימת **קו נייח** — `canonicalPhone` מחזיר '' לכל מה שאינו 05X, כי
//      בנתוני המקור יושב קו נייח ששבע הספרות שלו זהות לנייד של עובד אחר,
//      ובלי זה ההתנגשות הייתה הופכת לגישה.
// ============================================================================

import { canonicalPhone, isLinkablePhone, samePhone } from "./phone.js";

// הנרמול הוא חלק מהחוזה של הקישור, ולכן הוא נגיש מכאן: קורא שמייבא
// `driverLink` לא צריך לדעת שהמימוש יושב בקובץ טהור נפרד.
export { canonicalPhone, isLinkablePhone, samePhone };

// הסטטוסים שמהם מותר לתבוע רשומה. **'revoked' אינו כאן** — וזו הנקודה:
// אחרי ניתוק, `userId` חוזר ל-null, ובלי החסימה הזו העובד שעזב היה מקשר
// את עצמו מחדש בלחיצה אחת. חזרה לפורטל דורשת פעולה מפורשת של אדמין.
export const LINKABLE_PORTAL_STATUS = ["none", "invited"];

// ============================================================================
// isLinkable — האם המחובר רשאי לתבוע את הרשומה הזו.
//
// `phoneNumber` הוא `user.phoneNumber` מ-`onAuthStateChanged`, כלומר **בדיוק**
// מה שיגיע לכלל כ-`request.auth.token.phone_number`. אין כאן פרמטר
// `verified` מקביל ל-`emailVerified`: בכניסת טלפון, קיום המספר בטוקן **הוא**
// האימות (ראה ההערה בראש הקובץ).
// ============================================================================
export function isLinkable(driver, { phoneNumber } = {}) {
  if (!driver) return false;
  const mine = canonicalPhone(phoneNumber);
  if (!mine) return false; // אין מספר בטוקן, או מספר שאינו נייד ישראלי
  // השוואה **קנונית** משני הצדדים: המספר ברשומה הוקלד ביד ויכול להיות
  // 050-1234567, והטוקן חוזר תמיד +972501234567. אותה השוואה בדיוק מבוצעת
  // ב-firestore.rules (canonPhone).
  if (!samePhone(driver.phone, mine)) return false;
  if (driver.userId) return false; // רשומה שכבר מקושרת אינה נתפסת מחדש
  if (!LINKABLE_PORTAL_STATUS.includes(driver.portalStatus || "none")) return false;
  if (driver.status === "archived") return false;
  return true;
}

// findLinkableDriver — הרשומה שהמשתמש הזה רשאי לתבוע. `null` = אין כזו,
// וזה מצב תקין לחלוטין (מישהו שאינו עובד נכנס לקישור).
export function findLinkableDriver(drivers, user) {
  return (drivers || []).find((d) => isLinkable(d, user)) || null;
}

// הנהג שכבר מקושר ל-uid הזה ופעיל. זו הבדיקה שכל שאר המערכת נשענת עליה,
// והיא **לא** נוגעת בטלפון — F1.
export function linkedDriverForUid(drivers, uid) {
  if (!uid) return null;
  return (
    (drivers || []).find(
      (d) => d.userId === uid && d.portalStatus === "active" && d.status !== "archived"
    ) || null
  );
}

// ============================================================================
// linkFields / unlinkFields — **בדיוק** השדות שנכתבים, ולא אובייקט שלם.
//
// כלל ה-rules דורש `affectedKeys().hasOnly([...])`: הנהג רשאי לקבוע את
// ה-uid שלו ותו לא. אילו הקליינט היה שולח את הרשומה כולה (setDoc/merge על
// מודל שבזיכרון), הכתיבה הייתה נדחית — או גרוע מכך, הייתה עוברת בכלל
// רופף ומאפשרת לעובד לערוך את המחלקה, מספר העובד או ה-notes של עצמו.
//
// ⚠️ `portalLinkedEmail` **אינו** ברשימה יותר. הוא נשאר בסכימה לתיעוד
// היסטורי, אבל אינו ניתן לכתיבה במסלול הקישור — אחרת היה נוצר חור קטן
// ומוזר: נהג שכותב לעצמו כתובת מייל שרירותית ברשומה שלו.
// ============================================================================
export const LINK_WRITABLE_KEYS = ["userId", "portalStatus", "portalLinkedPhone", "updatedAt"];

// portalLinkedPhone — המספר שאיתו נכנס **בפועל**, לתיעוד בלבד (3.2.1).
// `phone` הוא מה שהאדמין הקליד; זה מה ש-Firebase אימתה ב-SMS. השניים נבדלים
// לגיטימית בצורת הכתיבה. הכלל אוכף שהערך הוא באמת המספר שבטוקן, ושהוא
// בפורמט E.164 — ולא מחרוזת חופשית.
export function linkFields(uid, phoneNumber, at) {
  return {
    userId: uid,
    portalStatus: "active",
    portalLinkedPhone: canonicalPhone(phoneNumber),
    updatedAt: at,
  };
}

// ניתוק: `userId` מתאפס ו-`portalStatus` נצרב 'revoked'. שני החלקים נחוצים —
// איפוס ה-uid לבדו היה מחזיר את הרשומה למצב שאפשר לתבוע מחדש.
export function unlinkFields(at) {
  return { userId: null, portalStatus: "revoked", portalLinkedPhone: null, updatedAt: at };
}

// הזמנה מחדש — הפעולה המפורשת שמחזירה רשומה מנותקת למצב שניתן לקישור.
export function inviteFields(at) {
  return { portalStatus: "invited", invitedAt: at, updatedAt: at };
}

// ============================================================================
// validateDriverLinkPhone — מה שהמסך חוסם לפני שה-rules ידחו.
//
// שני מצבים, ושניהם נראים בפרודקשן:
//   • מספר שאינו נייד ישראלי (קווי, חסר ספרה, זר) — לא ניתן לקישור בכלל.
//     ⚠️ זו אינה "ולידציה מחמירה": מספר כזה פשוט לא יקבל SMS מהפרויקט
//     (ה-region policy נעולה לישראל), והעובד היה נתקע במסך בלי הסבר.
//   • שני נהגים עם אותו מספר — שני עובדים שנלחמים על אותה רשומה, והראשון
//     שנכנס זוכה. ההשוואה קנונית, אחרת `050-1234567` ו-`0501234567` היו
//     עוברים כשני אנשים.
//
// מחזיר מערך מפתחות שגיאה (i18n); ריק = תקין. מספר **ריק** תקין — נהג בלי
// נייד הוא רשומה לגיטימית, היא פשוט אינה ניתנת לקישור.
// ============================================================================
export function validateDriverLinkPhone(drivers, driverId, phone) {
  const raw = String(phone ?? "").trim();
  if (!raw) return [];
  if (!isLinkablePhone(raw)) return ["driverLink.err.phone"];
  // ⚠️ **רק מול נהגים שאינם מאורכבים.** מספר של עובד שעזב מתפנה: החסימה
  // כאן אמורה למנוע שני עובדים **פעילים** על אותו מספר, ולא למנוע מהמחליף
  // לקבל את המספר של מי שעזב. (בארכוב `portalLinkedPhone` מתאפס מיד, ולכן
  // אין עקבת זהות שתתנגש.)
  const clash = (drivers || []).some(
    (d) => d.id !== driverId && d.status !== "archived" && d.phone && samePhone(d.phone, raw)
  );
  return clash ? ["driverLink.err.duplicate"] : [];
}

// ============================================================================
// phoneCollisions — **האינוריאנט, כפונקציה שאפשר לבדוק.**
//
// מחזיר מערך של `{ phone, driverIds }` לכל צורה קנונית שיושבת על יותר מנהג
// לא-מאורכב אחד. ריק = תקין.
//
// ⚠️ זו אינה ולידציית טופס, וזו הסיבה שהיא נפרדת מ-`validateDriverLinkPhone`:
// הטופס חוסם את ההקלדה **הבאה**, והפונקציה הזו בודקת את **מה שכבר בבסיס
// הנתונים** — כולל 27 הרשומות שיובאו מאקסל. בנתוני המקור היו ארבע התנגשויות
// (שלוש רשומות עם אותן שבע ספרות, ושני עובדים עם מספר משותף אמיתי), והן
// תוקנו ביד. הפונקציה הזו היא מה שיתפוס את הייבוא הבא.
//
// ⚠️ ההשוואה היא על הצורה הקנונית בלבד: `050-1234567` ו-`0501234567` הם
// התנגשות, ובדיקה שמשווה מחרוזות הייתה מפספסת אותה.
// ============================================================================
export function phoneCollisions(drivers) {
  const byPhone = new Map();
  for (const d of drivers || []) {
    if (!d || d.status === "archived") continue;
    const c = canonicalPhone(d.phone);
    if (!c) continue;
    byPhone.set(c, [...(byPhone.get(c) || []), d.id]);
  }
  return [...byPhone.entries()]
    .filter(([, ids]) => ids.length > 1)
    .map(([phone, driverIds]) => ({ phone, driverIds }));
}
