// ============================================================================
// phone.js — **canonicalPhone**: נרמול מספר נייד ישראלי ל-E.164, כלוגיקה טהורה.
//
// ============================================================================
// למה זה נולד: עוגן הזהות של פורטל הנהג עבר ממייל לנייד
// ============================================================================
// המודל הקודם נשען על `token.email` + `token.email_verified`. הוא עבד בכללים
// ועבר 328 בדיקות — אבל **אף נהג לא נקשר בפועל**: `portalStatus` של כל 27
// הנהגים נשאר `none`. לחברה אין חשבונות Google ארגוניים, והבקשה "תן לי את
// כתובת הגימייל הפרטית שלך" היא חסם שאף עובד לא עבר. הנייד, לעומת זה, כבר
// יושב בכרטיס הנהג, והעובד מקיש קוד SMS ונכנס.
//
// ⚠️ **זו החלפה, לא הוספה.** מסלול הקישור במייל הוסר מפורטל הנהג לחלוטין
// (ראה driverLink.js). dual-anchor היה מכפיל את משטח התקיפה ב-rules בלי
// להוסיף נהג אחד — וזו ההעדפה המפורשת של עדי.
//
// ⚠️ **האדמינים נשארו על מייל + Google.** `org.adminEmails` מול `token.email`
// ו-`email_verified` — לא נגענו בזה, וגם `admins.js` לא השתנה. ההפרדה הזו
// היא העיקר: שני עוגני זהות לשתי אוכלוסיות, כל אחד בנתיב הכללים שלו.
//
// ============================================================================
// ⚠️ **פונקציה אחת, חמש נקודות קריאה** (עדי, סקירת 1.10.2026 §5.2)
// ============================================================================
//   1. התאמת קישור       — driverLink.js:isLinkable
//   2. אכיפת ייחודיות    — driverLink.js:validateDriverLinkPhone
//   3. **כלל ה-rules**   — firestore.rules:canonPhone
//   4. רדקציה            — retention.js:redactDriverIdentifiersEverywhere
//   5. ייבוא             — importExcel.js (נרמול בקליטה)
//
// (3) הוא העדין: `canonPhone` ב-rules ו-`canonicalPhone` כאן הן שתי מימושות
// של אותו כלל, וכל סטייה ביניהן היא "הרשאה שלא עובדת" או הרשאת יתר. לכן
// מקטע (ח) ב-scripts/rules-test.mjs מריץ **את אותו מערך קלט בשני הצדדים**
// מול האמולטור — ולא מסתפק בקריאה בעיניים.
//
// ⚠️ וגם: אין כאן שתי פונקציות במקביל (`normalizePhone` + `canonicalPhone`)
// כמו ב-admins.js. לנייד יש **צורה קנונית אחת**, ושני שמות לאותו דבר הם
// ההזמנה הבטוחה ביותר לכך שקריאה אחת תשתמש בגרסה הלא-נכונה.
//
// ============================================================================
// למה E.164 ולא "מה שהאדמין הקליד"
// ============================================================================
// `token.phone_number` של Firebase חוזר **תמיד** בפורמט E.164 (`+9725…`).
// המספר שבכרטיס הנהג מוקלד בידיים, ולכן הוא יכול להיות `050-1234567`,
// `050 123 4567`, `0501234567` או `+972-50-123-4567` — ארבע מחרוזות לאותו
// אדם. השוואת מחרוזות בין הטוקן לרשומה חייבת לעבור דרך **צורה אחת**, אחרת
// הקישור נכשל בלי שאיש יבין למה. זה בדיוק מה ש-canonEmail עושה לגימייל,
// ומאותה סיבה.
// ============================================================================

// -- נרמול -----------------------------------------------------------------

// digitsOf — רק ספרות. רווחים, מקפים, סוגריים, נקודות, תו `+` ו-RTL marks
// נעלמים.
//
// ⚠️ **וגם גרש מוביל** — `'0540000017`. זו מלכודת ייבוא אמיתית ולא תיאורטית:
// אקסל שומר מספר שמתחיל ב-0 כטקסט עם גרש מוביל, כדי שהאפס לא ייעלם. בלי
// השורה הזו המספר הזה היה "מספר שאינו ניתן לקישור" בלי שאיש יבין למה.
export function digitsOf(raw) {
  return String(raw ?? "").replace(/[^0-9]/g, "");
}

// ============================================================================
// canonicalPhone — המחרוזת הקנונית, או `""` אם זה **אינו נייד ישראלי תקין**.
//
// `""` הוא תשובה לגיטימית ומלאת-משמעות: **קו נייח** (03-…), מספר חסר, או
// מספר זר — כולם "לא ניתנים לקישור". הקוד שמעלה אינו צריך לדעת למה.
//
// ⚠️ חסימת הקו הנייח היא דרישה מפורשת (עדי §2.2.4): קו נייח בשדה `phone`
// הוא פרט קשר תקין לחלוטין — הוא פשוט **אינו עוגן זהות**, והוא גם לא יקבל
// SMS. ובנתוני המקור שלנו יושב **קו נייח ששבע הספרות שלו זהות לנייד של
// עובד אחר** — בלי החסימה הזו ההתנגשות הייתה הופכת לגישה. (כל המספרים
// בדוגמאות ובבדיקות בדויים.)
//
// שלוש הצורות שמתקבלות, וכולן מתכנסות לאותו פלט:
//   0501234567        → +972501234567
//   +972-50-123-4567  → +972501234567
//   00972501234567    → +972501234567
// ============================================================================
export function canonicalPhone(raw) {
  let d = digitsOf(raw);
  if (!d) return "";
  // קידומת יציאה בינלאומית — 00972 ו-972 מתכנסות לאותו דבר.
  if (d.startsWith("00972")) d = d.slice(5);
  else if (d.startsWith("972")) d = d.slice(3);
  else if (d.startsWith("0")) d = d.slice(1);
  else return ""; // בלי 0 מוביל ובלי 972 — אין על מה להכריע, ולא ממציאים
  // המספר הלאומי: 9 ספרות שמתחילות ב-5 (כלומר 05X בצורה המקומית) — נייד
  // בלבד. כל קידומת אחרת (2/3/4/7/8/9) היא קו נייח או שירות, ונדחית.
  if (!/^5[0-9]{8}$/.test(d)) return "";
  return `+972${d}`;
}

// isLinkablePhone — האם מהמספר הזה אפשר לבנות זהות. השם מכוון: זו אינה
// "ולידציה של טלפון" (קו נייח תקין לחלוטין כמספר קשר) אלא בדיקה אחת —
// האם Firebase Auth יכול להנפיק עליו טוקן שיתאים לרשומה.
export function isLinkablePhone(raw) {
  return canonicalPhone(raw) !== "";
}

// samePhone — ההשוואה היחידה שמותר להשתמש בה בין טוקן לרשומה.
// שתי מחרוזות ריקות **אינן** אותו מספר: `samePhone("", "")` הוא false, אחרת
// נהג בלי טלפון היה מותאם לטוקן בלי טלפון, ושני קווים נייחים היו "אותו אדם".
export function samePhone(a, b) {
  const x = canonicalPhone(a);
  return x !== "" && x === canonicalPhone(b);
}

// ============================================================================
// formatPhoneIl — **תצוגה** בלבד: `+972501234567` → `050-123-4567`.
//
// למה: הצורה הקנונית היא מה שנשמר ומושווה, אבל אף אחד בארץ לא קורא מספר
// בפורמט E.164 בעין. מספר שאינו נייד ישראלי מוחזר כפי שהוא — זה שדה קשר
// חופשי, ולא תפקידה של פונקציית תצוגה לשפוט אותו.
// ============================================================================
export function formatPhoneIl(raw) {
  const e164 = canonicalPhone(raw);
  if (!e164) return String(raw ?? "").trim();
  const d = e164.slice(4); // 9 ספרות: 5XXXXXXXX
  return `0${d.slice(0, 2)}-${d.slice(2, 5)}-${d.slice(5)}`;
}

// ============================================================================
// numericRuns — **כל רצף ספרות בטקסט חופשי, כיחידה שלמה.**
//
// זו התשתית של הרדקציה (retention.js) ושל הבדיקה שמאמתת אותה, והיא הדרך
// לעמוד בדרישה הקשה של עדי (§5.1): **אין regex כללי לטלפון.**
//
// רצף ספרות הוא **מקסימלי** — הוא נתחם בתו שאינו ספרה-או-מפריד, או בקצה
// המחרוזת. זה מה שמייצר את שלוש ההגנות בבת אחת:
//   • **אין התאמה חלקית.** שבע הספרות של נייד לעולם אינן רצף שלם בתוך
//     קו נייח (`03-…` + אותן שבע ספרות), ולכן הקו הנייח של עובד אחר אינו
//     נוגע בו.
//   • **גבולות רצף.** `0540000017` בתוך `+9720540000017` אינו רצף שלם,
//     ולכן הוא אינו מטופל (וגם לא פעמיים).
//   • **לוחיות רישוי ואסמכתאות שורדות.** לוחית בת 8 ספרות היא רצף שלם — והצורה
//     הקנונית שלו היא `''`, ולכן הוא מעולם לא מושווה למספר של אף אחד.
//
// החלוקה לתת-רצפים לפי רווח היא הפשרה היחידה: `"050-1234567 5000 ק\"מ"` הוא
// רצף מקסימלי אחד (רווח הוא מפריד לגיטימי בתוך `054 000 0017`), ובלי השלב
// הזה המספר היה **נמלט מהרדקציה**. בדיקת השוויון הקנוני נשארת זהה, ולכן
// הפירוק אינו מרחיב את מה שמותר להחליף — רק את מה שנבדק.
// ============================================================================
const NUMERIC_RUN = /[+0-9][0-9+\s().-]*[0-9]|[0-9]/g;

// mapNumericRuns — מעביר כל רצף דרך `fn`, ומחזיר את הטקסט עם מה ש-fn החזיר.
// `fn(run)` מקבל מחרוזת ומחזיר מחרוזת (או null = "אל תיגע").
export function mapNumericRuns(text, fn) {
  return String(text ?? "").replace(NUMERIC_RUN, (run) => {
    const whole = fn(run);
    if (whole !== null && whole !== undefined) return whole;
    if (!/\s/.test(run)) return run;
    // תת-רצפים: שומרים את המפרידים במקומם (split עם קבוצה לוכדת).
    return run
      .split(/(\s+)/)
      .map((part) => {
        if (/^\s+$/.test(part) || !part) return part;
        const sub = fn(part);
        return sub === null || sub === undefined ? part : sub;
      })
      .join("");
  });
}

// canonicalPhonesIn — כל הצורות הקנוניות שמופיעות בטקסט. זו הפונקציה שבדיקת
// M1 נשענת עליה: היא **מחלצת ומקננת**, ולא מחפשת מחרוזת. בדיקה שמחפשת
// `0540000017` עוברת בהצלחה גם כשבטקסט יושב `054-000-0017` — אותו אדם, אותו
// מזהה, שתי מחרוזות (עדי §5.4).
export function canonicalPhonesIn(text) {
  const found = new Set();
  mapNumericRuns(text, (run) => {
    const c = canonicalPhone(run);
    if (c) found.add(c);
    return null; // סריקה בלבד, בלי שינוי
  });
  return found;
}

// ============================================================================
// phoneQueryForms — הצורות שבהן המספר **יכול להיות שמור** ב-Firestore.
//
// ⚠️ זו הנקודה שהכי קל לפספס בהחלפה הזו, ולכן היא כתובה: שאילתת Firestore
// היא **השוואת מחרוזות מדויקת**, ואין בה נרמול. הכלל בצד השרת כן מנרמל
// (`canonPhone`), ולכן מסמך ששמור כ-`050-1234567` **מותר** לקריאה — אבל
// `where('phone','==','+972501234567')` לא יחזיר אותו בכלל.
//
// 27 רשומות הנהגים כבר בענן, והטלפון בהן הוקלד ביד לפני שהיה לו תפקיד.
// לכן הפורטל מחפש כמה צורות, בדיוק כפי שמסלול המייל חיפש גם raw וגם canon.
// הרשימה סגורה ומסודרת לפי סבירות, וה-UI מנרמל בשמירה (DriverForm) כדי
// שהנתונים יתכנסו מעצמם לצורה הראשונה.
//
// ⚠️ שאילתה שאינה מחזירה מסמכים אינה "דחייה" — היא פשוט ריקה, ולכן ריבוי
// הצורות אינו מרחיב שום הרשאה: כל מסמך שכן יחזור עובר את אותו כלל.
// ============================================================================
export function phoneQueryForms(raw) {
  const e164 = canonicalPhone(raw);
  if (!e164) return [];
  const d = e164.slice(4); // 5XXXXXXXX
  return [
    ...new Set([
      e164, // +972501234567  ← מה שה-UI שומר מעכשיו
      `0${d}`, // 0501234567
      `0${d.slice(0, 2)}-${d.slice(2)}`, // 050-1234567
      `0${d.slice(0, 2)}-${d.slice(2, 5)}-${d.slice(5)}`, // 050-123-4567
      `0${d.slice(0, 2)} ${d.slice(2)}`, // 050 1234567
    ]),
  ];
}
