// ============================================================================
// fingerprint.ts — מפתח תוכן להזמנה, נגזר **מהחלק החתום בלבד**.
//
// ---------------------------------------------------------------------------
// ★ למה לא `Message-ID`
// ---------------------------------------------------------------------------
// תג ה-`h=` בחתימה של ספק הסליקה מכסה `Received:From:To:Subject` — ו**לא**
// את `Message-ID`. כלומר אפשר לקחת הודעת עסקה אמיתית וחתומה, לשנות בה את
// המזהה, ולשלוח אותה שוב: החתימה עדיין עוברת, וכל מנגנון שמזהה כפילות לפי
// מזהה בלבד רואה שתי הזמנות שונות.
//
// זה לא באג תיאורטי. במוצר הזה כפילות שלא נתפסה פירושה **חבילה שנייה שנארזת
// ויוצאת** על חשבון בעלת העסק, בלי שאף אחד שילם עליה פעמיים.
//
// לכן מפתח הכפילות נגזר מ**התוכן החתום**: שתי הודעות שהגוף החתום שלהן זהה
// הן אותה הזמנה, בלי קשר למזהה שלהן.
//
// ---------------------------------------------------------------------------
// ★ מה זה **לא**
// ---------------------------------------------------------------------------
// זו אינה פונקציית גיבוב קריפטוגרפית ואין לה תפקיד אבטחתי. היא לא מגינה על
// שום דבר, ואי אפשר "לזייף" אותה לרעה: התוצאה היחידה של התנגשות היא
// שהזמנה תסומן "צריך שתסתכלי" — כלומר הכיוון הבטוח. הבחירה ב-FNV-1a היא כי
// היא דטרמיניסטית, זהה בכל סביבה, ולא גוררת שום תלות.
//
// ★ שני סיבובים עם offset שונה, ולא אחד: 32 סיביות בודדות מייצרות התנגשות
// אקראית בסבירות שאינה זניחה על פני אלפי הזמנות, וכל התנגשות כזאת היא הזמנה
// אמיתית שנעצרת לבדיקה בלי סיבה.
//
// ---------------------------------------------------------------------------
// ⚠️ המחיר, וזה מכוון
// ---------------------------------------------------------------------------
// לקוחה שהזמינה **פעמיים את אותו דבר בדיוק** יכולה לייצר שתי הודעות עם גוף
// חתום זהה, ואז ההזמנה השנייה תסומן ככפילות. זו הטעות שאנחנו בוחרים לעשות:
// "תפתחי ותוודאי" עולה דקה, ו"נשלחה חבילה כפולה" עולה משלוח.
// ============================================================================

const OFFSET_A = 0x811c9dc5;
const OFFSET_B = 0x01000193;
const PRIME = 0x01000193;

function fnv1a(bytes: readonly number[], offset: number): number {
  let hash = offset >>> 0;
  for (const b of bytes) {
    hash ^= b;
    hash = Math.imul(hash, PRIME) >>> 0;
  }
  return hash >>> 0;
}

function utf8Bytes(raw: string): number[] {
  const out: number[] = [];
  for (const ch of raw) {
    const cp = ch.codePointAt(0) ?? 0;
    if (cp < 0x80) out.push(cp);
    else if (cp < 0x800) out.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f));
    else if (cp < 0x10000)
      out.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
    else
      out.push(
        0xf0 | (cp >> 18),
        0x80 | ((cp >> 12) & 0x3f),
        0x80 | ((cp >> 6) & 0x3f),
        0x80 | (cp & 0x3f),
      );
  }
  return out;
}

/**
 * ★ נרמול לפני הגיבוב.
 *
 * רווחים, שורות ריקות ותווי שורה נשברים בין מעבר לממסר לבין הצגה, ואינם
 * חלק ממה שההזמנה **אומרת**. בלי הנרמול, אותה הזמנה בדיוק שעברה דרך שני
 * מסלולים הייתה מקבלת שני מפתחות — כלומר המנגנון היה קיים ולא עובד.
 */
function normalize(raw: string): string {
  return String(raw ?? '')
    .normalize('NFKC')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * מפתח תוכן יציב. מחרוזת ריקה מחזירה `null` — אין תוכן, אין מפתח, ובוודאי
 * שאין "כל ההודעות הריקות זהות זו לזו".
 */
export function contentFingerprint(raw: string): string | null {
  const text = normalize(raw);
  if (!text) return null;
  const bytes = utf8Bytes(text);
  const a = fnv1a(bytes, OFFSET_A).toString(16).padStart(8, '0');
  const b = fnv1a(bytes, OFFSET_B).toString(16).padStart(8, '0');
  return `${a}${b}`;
}
