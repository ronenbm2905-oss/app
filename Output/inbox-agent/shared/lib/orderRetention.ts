// ומבקשת שימחקו את הפרטים שלה. הספק מוחק, היא מקבלת אישור, ומבחינתה הנושא
// סגור. **העותק שלנו נשאר.**
//
// אין כאן באג — יש כאן עותק שאף אחד לא זכר שהוא קיים. וזה בדיוק המצב שבו
// בעלת העסק מוצאת את עצמה מצהירה בתום לב הצהרה לא נכונה.
//
// לכן: פונקציה טהורה שמוחקת לפי מייל או שם, ומחזירה **כמה נמחקו**. היא לא
// מחזירה את הרשומות שנמצאו ולא מציגה אותן — מסך שמראה "מצאתי 3 הזמנות של
// דנה" הוא מסך שמאפשר לחפש אנשים במאגר, וזו בדיוק היכולת שאנחנו מנסים
// לצמצם.

export interface PurgeRequestResult {
  orders: Order[];
  /** כמה רשומות נמחקו בפועל. */
  purgedCount: number;
  /** משפט מוכן להצגה. */
  messageHe: string;
}

/** נרמול לצורך השוואה: אותיות קטנות, בלי רווחים כפולים. */
function normalizeQuery(s: string): string {
  return String(s ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * ★ האם הרשומה שייכת לנושא המידע שביקש למחוק.
 *
 * התאמה על **מייל מלא** או על **שם מלא**, ולא התאמה חלקית. `includes` היה
 * הופך חיפוש של "דנה" למחיקה של כל מי ששמה מכיל "דנה" — וזו מחיקה של מידע
 * של אנשים אחרים בתגובה לבקשה של אחד. מחיקה בלתי-הפיכה דורשת התאמה מדויקת.
 */
export function matchesDataSubject(order: Order, query: string): boolean {
  const q = normalizeQuery(query);
  if (!q || order.recipientPurged) return false;
  const { email, name } = order.recipient;
  return normalizeQuery(email ?? '') === q || normalizeQuery(name ?? '') === q;
}

/**
 * מוחקת את פרטי הנמענת מכל ההזמנות של נושא מידע אחד. מיידית, בלי להמתין
 * לשעון.
 *
 * ★ מה **לא** נמחק: התאריך, המוצר, הכמות והסכום — כלומר רשומת המכירה. זו
 * לא התחמקות אלא ההפרדה שהמבנה בנוי עליה: לבקשת מחיקה של מידע אישי אין
 * כוח למחוק חובת תיעוד חשבונאית, והרשומה המצומצמת אינה מזהה איש.
 */
export function purgeByRequest(
  orders: readonly Order[],
  query: string,
  opts: RetentionOptions = {},
): PurgeRequestResult {
  const q = normalizeQuery(query);
  if (!q) {
    return {
      orders: [...orders],
      purgedCount: 0,
      messageHe: 'צריך למלא מייל או שם מלא כדי שאדע מה למחוק',
    };
  }

  let purgedCount = 0;
  const out = orders.map((o) => {
    if (!matchesDataSubject(o, q)) return o;
    purgedCount++;
    return purgeRecipient(o, opts);
  });

  return {
    orders: out,
    purgedCount,
    messageHe:
      purgedCount === 0
        ? 'לא מצאתי הזמנה עם המייל או השם הזה. אם היא מלפני חצי שנה, ייתכן שהפרטים כבר נמחקו מעצמם'
        : purgedCount === 1
          ? 'מחקתי את פרטי המשלוח בהזמנה אחת. נשארו התאריך, המוצר, הכמות והסכום'
          : `מחקתי את פרטי המשלוח ב-${purgedCount} הזמנות. נשארו התאריך, המוצר, הכמות והסכום`,
  };
}

