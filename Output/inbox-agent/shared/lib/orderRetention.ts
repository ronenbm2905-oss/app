//
// ---------------------------------------------------------------------------
// ★★ למה המזעור כאן ולא ב"מה לא לאסוף"
// ---------------------------------------------------------------------------
// בכל שאר המערכת המזעור נראה כמו רשימת שדות שלא נשמרים. בהזמנה זה לא עובד:
// **הכתובת אינה תופעת לוואי, היא המוצר.** בלי שם, רחוב, עיר ומיקוד אין
// משלוח, ולכן "לא לאסוף" פירושו לבטל את הפיצ׳ר.
//
// המזעור עובר מ**מה** ל**מתי**, ויש **שני שעונים** שרצים במקביל:
//
//   שולח:  purgeAfter = shippedAt  +  60 יום
//   רצפה:  purgeAfter = receivedAt + 180 יום   ★ בלי קשר לסטטוס
//   בפועל: המוקדם מבין השניים.
//
//   אחרי purgeAfter → **פרטי הנמענת נמחקים**, ונשארת רשומה מצומצמת:
//                     תאריך · מוצר · כמות · סכום.
//
// ---------------------------------------------------------------------------
// ★★ למה יש רצפה — הכשל שהיה במדיניות הראשונה
// ---------------------------------------------------------------------------
// הניסוח הראשון היה "כל עוד לא נשלח — הכול נשמר". הוא נשמע סביר עד שסקירת
// עדי הצביעה על מה שהוא אומר בפועל: **הזמנה שאף אחד לא סימן מחזיקה כתובת
// מגורים לנצח.** כלומר כל סכימת המחיקה נשענת על כך שאדם עסוק יזכור ללחוץ על
// צ׳קבוקס — וזה בדיוק מה שלא קורה עם ההזמנה שהתבטלה, עם זו שטופלה בטלפון,
// ועם זו שנפלה בין הכיסאות. בקרה שתלויה בזיכרון אינה בקרה.
//
// 180 יום הם המספר שממנו והלאה "עוד לא שלחתי" מפסיק להיות מצב תפעולי והופך
// לשכחה. ולכן היא מגיעה עם **רשימה גלויה 30 יום מראש** (`expiringSoon`): לא
// מחיקה שקטה, אלא "ההזמנות האלה יימחקו בקרוב — אם משהו כאן עוד פתוח, טפלי
// בו עכשיו".
//
// ---------------------------------------------------------------------------
// ★ 60 הימים: המספר נשאר, השם משתנה — וזה לא ויכוח סמנטי
// ---------------------------------------------------------------------------
// קראנו לזה קודם "חלון ההחזרות". זו הייתה **טענה משפטית שגויה**: חוק הגנת
// הצרכן נותן ארבעה חודשים לאדם עם מוגבלות, לאזרח ותיק ולעולה חדש, ו-60 יום
// לא מכסים אותם. מדיניות שנקראת על שם חלון משפטי מצהירה שהיא מכסה אותו —
// והצהרה שגויה גרועה מהיעדר הצהרה.
//
// הנימוק הנכון פשוט יותר, וגם חזק יותר: **האפליקציה אינה הרשומה.** הרשומה
// המחייבת חיה במערכת הסליקה ואצל הרו״ח, ושתיהן שומרות אותה לפי החובות שלהן.
// מה שיושב כאן הוא **עותק עבודה לצורך אריזה ומשלוח**, ולעותק עבודה אין סיבה
// לשרוד את המשימה שלו. לקוחה שתחזור בעוד חצי שנה — התשובה נמצאת במקום שבו
// היא אמורה להיות, לא כאן.
//
// ★ שני המספרים הם קבועים במקום אחד ומוזרקים לכל הפונקציות.
//
// ---------------------------------------------------------------------------
// ★ הבקרה הזאת מחזיקה שני דברים בבת אחת
// ---------------------------------------------------------------------------
// **תפעולית:** רשימת "מה לשלוח היום" שמצטברת לנצח מפסיקה להיות רשימה. אחרי
// חצי שנה היא מסך עם 400 כרטיסים שאף אחד לא גולל.
//
// **משפטית:** כל לקוחה חדשה היא נושא מידע נוסף, ובחנות זה מצטבר מהר. מאגר
// שמוחק מעצמו הוא הטענה החזקה ביותר שיש מול השאלה "כמה זמן אתם שומרים".
//
// ⚠️ הלקח שנרשם ב-`Output/hachzarei-mas/functions/src/index.ts` חל כאן מילה
// במילה: שם `purgeAfter` **נכתב ואף אחד לא קרא אותו** — כלומר המדיניות
// הצהירה על מחיקה שלא קרתה. לכן `applyRetention` נקראת בכל טעינה של המסך,
// ולא "בתהליך רקע שיהיה". מדיניות שאין לה קוד שמריץ אותה היא טקסט.
//
// ---------------------------------------------------------------------------
// הפיכות — ולמה יש לה גבול שאי אפשר לעקוף
// ---------------------------------------------------------------------------
// סימון "נשלח" הפיך בלחיצה (`unmarkShipped`), וזו הבקרה שמאפשרת לסמוך על
// צ׳קבוקס. אבל **אחרי המחיקה אין חזרה**, וזה לא באג: הפיכות שמשחזרת מידע
// שנמחק פירושה שהוא לא נמחק. לכן `unmarkShipped` על רשומה שנמחקה מחזירה
// אותה למצב 'ממתין' **בלי הכתובת**, והמסך אומר את זה במפורש במקום להציג
