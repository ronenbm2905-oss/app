import type { Order } from '../types/order';
import { EMPTY_RECIPIENT } from '../types/order';

/**
 * ★ כמה זמן העותק נשאר **אחרי שהחבילה יצאה**.
 * שם השדה מתאר את מה שהוא באמת — זמן אחרי משלוח — ולא חלון משפטי שהוא לא
 * מכסה. ראה ההערה בראש הקובץ.
 */
export const POST_SHIPMENT_DAYS = 60;

/** ★★ הרצפה. מקסימום זמן שרשומה קיימת, בלי קשר לשום סטטוס. */
export const MAX_RETENTION_DAYS = 180;

/** כמה ימים מראש ההזמנה מופיעה ברשימת "עומדות להימחק". */
export const PURGE_WARNING_DAYS = 30;

const DAY_MS = 24 * 60 * 60 * 1000;

export interface RetentionOptions {
  /** "עכשיו". מוזרק תמיד, כדי שמבחן לא יהיה תלוי בשעון. */
  now?: Date | string;
  /** לדריסה במבחנים בלבד. */
  postShipmentDays?: number;
  /** לדריסה במבחנים בלבד. */
  maxRetentionDays?: number;
  /** לדריסה במבחנים בלבד. */
  warningDays?: number;
}

function asDate(v: Date | string | undefined | null): Date {
  if (v instanceof Date) return v;
  if (typeof v === 'string') {
    const d = new Date(v);
    if (!isNaN(d.getTime())) return d;
  }
  return new Date();
}

function isValidIso(v: string | null | undefined): boolean {
  return typeof v === 'string' && v.length > 0 && !isNaN(new Date(v).getTime());
}

// ---------------------------------------------------------------------------
// ★ חישוב תאריך המחיקה
// ---------------------------------------------------------------------------

/**
 * ★★ מתי הכתובת נמחקת. **המוקדם מבין שני השעונים.**
 *
 * `Math.min` ולא `if/else`, ובכוונה: כל ניסוח שבו הרצפה היא "מקרה אחר"
 * מייצר ענף שאפשר לשכוח. כאן אין מסלול שבו רשומה יוצאת בלי תאריך — אלא אם
 * `receivedAt` עצמו פגום, וזו תקלה ולא מדיניות.
 *
 * הפונקציה מקבלת מצב ולא רשומה מלאה, כדי שאפשר יהיה לקרוא לה גם לפני שיש
 * רשומה — למשל להציג "יימחק ב-" ליד צ׳קבוקס שעוד לא סומן.
 */
export function purgeDateFor(
  state: { status: Order['status']; shippedAt: string | null; receivedAt: string },
  opts: RetentionOptions = {},
): string | null {
  const postShipment = opts.postShipmentDays ?? POST_SHIPMENT_DAYS;
  const maxDays = opts.maxRetentionDays ?? MAX_RETENTION_DAYS;

  const candidates: number[] = [];

  // ★ הרצפה. חלה תמיד, על כל סטטוס.
  if (isValidIso(state.receivedAt)) {
    candidates.push(new Date(state.receivedAt).getTime() + maxDays * DAY_MS);
  }

  if (state.status === 'shipped' && isValidIso(state.shippedAt)) {
    candidates.push(new Date(state.shippedAt as string).getTime() + postShipment * DAY_MS);
  }

  if (candidates.length === 0) return null;
  return new Date(Math.min(...candidates)).toISOString();
}

// ---------------------------------------------------------------------------
// ★ סימון "נשלח" — וביטולו
// ---------------------------------------------------------------------------

/**
 * מסמנת הזמנה כנשלחה ומתחילה את השעון.
 *
 * ★ מחזירה **עותק חדש**. הרשומה הנכנסת לא משתנה — זה מה שמאפשר להשוות
 * "לפני" ו"אחרי" במבחן, ומה שמונע ממסך אחד לשנות נתון מתחת לרגליו של אחר.
 */
export function markShipped(order: Order, opts: RetentionOptions = {}): Order {
  const shippedAt = asDate(opts.now).toISOString();
  const next: Order = {
    ...order,
    status: 'shipped',
    shippedAt,
    updatedAt: shippedAt,
  };
  return { ...next, purgeAfter: purgeDateFor(next, opts) };
}

/**
 * ★ ביטול הסימון. הבקרה שמאפשרת לסמוך על הצ׳קבוקס.
 *
 * שים לב למה שהיא **לא** עושה: היא לא משחזרת כתובת שנמחקה. רשומה שנמחקה
 * חוזרת למצב 'ממתין' ריקה, ו-`recipientPurged` נשאר `true` כדי שהמסך ידע
 * להסביר את זה. השורה הזאת היא ההבדל בין "נמחק" לבין "הוסתר".
 */
export function unmarkShipped(order: Order, opts: RetentionOptions = {}): Order {
  const next: Order = {
    ...order,
    status: 'new',
    shippedAt: null,
    updatedAt: asDate(opts.now).toISOString(),
  };
  // ★ ולא `purgeAfter: null`. ביטול הסימון מחזיר את ההזמנה למסלול הרגיל,
  // **לא מוציא אותה מהמדיניות**. אחרת היה כאן מנגנון פשוט לשמירה לנצח:
  // לסמן, לבטל, ולהישאר בלי תאריך מחיקה.
  return { ...next, purgeAfter: purgeDateFor(next, opts) };
}

