/**
 * האם הגיע הזמן למחוק את פרטי הנמענת.
 *
 * ★ שים לב שאין כאן `status !== 'shipped' → false`. בגרסה הראשונה הוא היה,
 * כ"הגנת עומק" — ומרגע שנוספה הרצפה הוא **הפך למה שמבטל אותה**: הזמנה שלא
 * סומנה לעולם לא הייתה נמחקת, כלומר בדיוק המקרה שהרצפה נבנתה בשבילו.
 * זו דוגמה טובה לכך שהגנת עומק שלא נבדקה מול המדיניות החדשה היא חור.
 */
export function isDueForPurge(order: Order, opts: RetentionOptions = {}): boolean {
  if (order.recipientPurged) return false;
  if (!isValidIso(order.purgeAfter)) return false;
  return asDate(opts.now).getTime() >= new Date(order.purgeAfter as string).getTime();
}

/**
 * ★ מוחקת את פרטי הנמענת ומשאירה רשומה מצומצמת.
 *
 * מה נשאר, ולמה כל אחד מהם: **תאריך** (מתי נמכר), **מוצר וכמות** (מה נמכר
 * — זה מלאי, לא מידע אישי), **סכום** (כמה — זה הנהלת חשבונות). מה שיורד:
 * שם, טלפון, מייל, רחוב, עיר, מיקוד, מדינה. כלומר **הכול חוץ מהעסקה**.
 *
 * `id` ו-`sourceMessageId` נשארים בכוונה: הם מצביעים למייל המקורי בתיבה,
 * שהוא לא שלנו ולא נמחק על ידינו. בלעדיהם אי אפשר יהיה למצוא הזמנה ישנה
 * כשלקוחה מתקשרת — והמייל עצמו ממילא קיים.
 *
 * הפונקציה **אידמפוטנטית**: הרצה שנייה לא משנה כלום.
 */
export function purgeRecipient(order: Order, opts: RetentionOptions = {}): Order {
  if (order.recipientPurged) return order;
  return {
    ...order,
    recipient: { ...EMPTY_RECIPIENT },
    recipientPurged: true,
    updatedAt: asDate(opts.now).toISOString(),
  };
}

export interface RetentionRun {
  orders: Order[];
  /** מזהי ההזמנות שנמחקו בריצה הזאת. לתצוגה ולמבחן. */
  purgedIds: string[];
}

/**
 * ★ מריצה את המדיניות על כל הרשימה. **זו הפונקציה שאסור לשכוח לקרוא לה.**
 *
 * היא מתקנת גם `purgeAfter` שאינו עקבי עם המצב — למשל רשומה שנשמרה
 * בגרסה קודמת, או הזמנה שסומנה כנשלחה ואז המצב שלה שוחזר. הרשומה ה"נכונה"
 * נגזרת תמיד מ-`status` + `shippedAt`, שהם היחידים שהמשתמשת שולטת בהם.
 */
export function applyRetention(
  orders: readonly Order[],
  opts: RetentionOptions = {},
): RetentionRun {
  const purgedIds: string[] = [];
  const out = orders.map((order) => {
    const expected = purgeDateFor(order, opts);
    const synced: Order = order.purgeAfter === expected ? order : { ...order, purgeAfter: expected };
    if (!isDueForPurge(synced, opts)) return synced;
    purgedIds.push(synced.id);
    return purgeRecipient(synced, opts);
  });
  return { orders: out, purgedIds };
}

/**
 * ★ ההזמנות שעומדות להימחק בקרוב ועדיין לא יצאו.
 *
 * זו החצי השני של הרצפה, ובלעדיו הרצפה היא מלכודת: מחיקה אוטומטית של משהו
 * שהמשתמשת עוד מתכוונת לטפל בו, בלי שראתה שזה עומד לקרות. הרשימה הזאת היא
 * מה שהופך "נמחק לי" ל"הראיתי לך שלושים יום מראש".
 *
 * מסוננת ל-`status === 'new'` בכוונה: הזמנה שכבר יצאה **אמורה** להימחק, ואין
 * שום פעולה שהמשתמשת צריכה לעשות לגביה. התראה עליה הייתה רעש שמלמד להתעלם.
 */
export function expiringSoon(orders: readonly Order[], opts: RetentionOptions = {}): Order[] {
  const warnDays = opts.warningDays ?? PURGE_WARNING_DAYS;
  return orders.filter((o) => {
    if (o.status !== 'new' || o.recipientPurged) return false;
    const days = daysUntilPurge(o, opts);
    return days !== null && days <= warnDays;
  });
}

