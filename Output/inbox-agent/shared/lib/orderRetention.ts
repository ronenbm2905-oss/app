/** כמה ימים נשארו עד המחיקה. `null` כשאין מחיקה מתוכננת. */
export function daysUntilPurge(order: Order, opts: RetentionOptions = {}): number | null {
  if (!isValidIso(order.purgeAfter)) return null;
  const ms = new Date(order.purgeAfter as string).getTime() - asDate(opts.now).getTime();
  return Math.max(0, Math.ceil(ms / DAY_MS));
}

/**
 * ★ משפט אחד בעברית על מה שעומד לקרות למידע.
 *
 * מוצג ליד ההזמנה, ולא בעמוד מדיניות. משתמשת שרואה "פרטי המשלוח יימחקו
 * בעוד 47 יום" מבינה את מדיניות השמירה בלי לקרוא אותה — וזו הדרך היחידה
 * שבה מדיניות מגיעה למי שהיא נוגעת לה.
 */
export function retentionNoteHe(order: Order, opts: RetentionOptions = {}): string {
  if (order.recipientPurged) {
    return 'פרטי המשלוח של ההזמנה הזאת נמחקו. נשארו התאריך, המוצר, הכמות והסכום';
  }
  const days = daysUntilPurge(order, opts);
  if (order.status !== 'shipped') {
    // ★ גם כאן יש תאריך — הרצפה. הניסוח הישן ("נשמרים במלואם") היה נכון
    // לגבי מה שמוצג ושגוי לגבי מה שקורה, וזה בדיוק סוג המשפט שגורם
    // למשתמשת להיות מופתעת בעוד חצי שנה.
    if (days === null) return 'כל עוד ההזמנה לא יצאה, הפרטים נשמרים';
    return `כל עוד ההזמנה לא יצאה הפרטים נשמרים, ולכל היותר עוד ${days} ימים`;
  }
  if (days === null) return 'הפרטים יימחקו בסיום תקופת ההחזרות';
  if (days === 0) return 'פרטי המשלוח כאן יימחקו היום';
  if (days === 1) return 'פרטי המשלוח כאן יימחקו מחר';
  return `פרטי המשלוח כאן יימחקו בעוד ${days} ימים`;
}
