/**
 * ★ כל האוספים יושבים תחת `users/{uid}/`.
 *
 * לא בגלל multi-tenancy — יש משתמשת אחת — אלא כי זה הופך את כלל הבידוד
 * לכלל אחד שאי אפשר לשכוח: `match /users/{uid}/{document=**}` עם
 * `request.auth.uid == uid`. אוסף ברמת השורש דורש כלל משלו, וכלל שנשכח הוא
 * אוסף חשוף.
 */
export const USERS = 'users';

/**
 * ★ `state` של זרימת ההרשאה — **אוסף שורש, ולא תחת `users/{uid}`.**
 *
 * לא חריגה מהכלל אלא נגזרת ממנו: ה-`state` חוזר מגוגל **בלי ה-uid**, ולכן
 * צריך למצוא אותו לפי הערך שלו בלבד. אוסף מקונן היה מחייב `collectionGroup`
 * וחיפוש לפי מזהה מסמך — או, גרוע יותר, לקבל את ה-uid מהבקשה עצמה, ואז כל
 * אחד יכול לטעון שהוא כל אחד.
 *
 * ה-`state` הוא nonce אקראי ולא מידע על אדם. מה שהוא כן מחזיק — את ה-uid —
 * מוגן ב-rules: `allow read, write: if false`, כמו `oauthTokens`.
 */
export const OAUTH_STATES = 'oauthStates';

export const COLLECTIONS = {
  /** ★★ ה-refresh token המוצפן. `if false` מוחלט ב-rules. */
  oauthTokens: 'oauthTokens',
  /** ההזמנות. הקריאה — לבעלים בלבד. */
  orders: 'orders',
  /** ★ "ההזמנות של היום" — מזהים בלבד. ראה ההערה למטה. */
  dailyLists: 'dailyLists',
  /** ★★ B3′.2 / M15 — יומן הגישה שדורית רואה. */
  accessLog: 'accessLog',
  /** ריצות סנכרון: ספירות ושגיאות. **בלי תוכן.** */
  syncRuns: 'syncRuns',
} as const;

export type CollectionName = (typeof COLLECTIONS)[keyof typeof COLLECTIONS];

export const userDocPath = (uid: string): string => `${USERS}/${uid}`;
export const collectionPath = (uid: string, name: CollectionName): string =>
  `${USERS}/${uid}/${name}`;
export const docPath = (uid: string, name: CollectionName, id: string): string =>
  `${collectionPath(uid, name)}/${id}`;

/**
 * ★★ האוספים שמדיניות המחיקה **חייבת** לעבור עליהם.
 *
 * ---------------------------------------------------------------------------
 * למה זו רשימה מיוצאת ולא לולאה בתוך `purge.ts`
 * ---------------------------------------------------------------------------
 * זה הלקח מ-8א.2(ב) בסקירה, והוא הכשל שכבר קרה פעם אחת בפרויקט אחר:
 *
 * > *"מחיקת שדות במסמך ההזמנה אינה מספיקה אם קיים מסמך 'ההזמנות של היום'
 * > שמרנדר את הרשימה — **הוא מחזיק את אותן כתובות והוא לא ב-`orders/`,
 * > ולכן `purgeExpired` לא יעבור עליו.**"*
 *
 * הרשימה מיוצאת כדי ש**מבחן** יוכל לטעון עליה: `tests/purgeOrders.test.ts`
 * כותב כתובת לכל אחד מהאוספים כאן, מריץ purge, וסורק את כולם. אוסף שיתווסף
 * למוצר ולא יתווסף לרשימה — לא ייתפס על ידי הרשימה, אבל **כן** ייתפס על ידי
 * `RECIPIENT_FIELD_NAMES` למטה, שסורק בעיוורון.
 */
export const PURGE_SCOPE: readonly CollectionName[] = [
  COLLECTIONS.orders,
  COLLECTIONS.dailyLists,
];

/**
 * ★ שמות שדות שאסור שישרדו מחיקה, בשום מסמך.
 *
 * הסריקה הזאת היא **הרשת השנייה**: `PURGE_SCOPE` מכסה את מה שידענו לרשום,
 * והרשימה הזאת מכסה את מה ששכחנו. `purgeOrders` מוחקת כל שדה כזה בכל מסמך
 * שהיא נוגעת בו, ומדווחת על כל מחיקה כזאת כ**ממצא** — לא כניקוי שקט. מסמך
 * שהחזיק כתובת במקום שלא תכננו הוא באג בסכימה, וצריך לראות אותו.
 */
export const RECIPIENT_FIELD_NAMES: readonly string[] = [
  'name',
  'phone',
  'email',
  'street',
  'city',
  'postalCode',
  'countryCode',
  'recipient',
  'address',
  'fullName',
];

/**
 * ★ מסמך "ההזמנות של היום" — **מזהים וחותמות זמן בלבד.**
 *
 * זו אותה הכרעה שנעשתה ב-`localStorage` בפרוסה 0, מאותה סיבה בדיוק: מסמך
 * שמחזיק את הכרטיס המוכן הוא עותק שני של אותן כתובות, כזה שלא יושב
 * ב-`orders` ושאיש לא יזכור למחוק. כאן זה בלתי אפשרי מבנית — הרשימה היא
 * מצביעים, וכל פרט נקרא מ-`orders` שכבר עבר את המדיניות.
 *
 * ומעל זה, החגורה: האוסף בכל זאת ב-`PURGE_SCOPE`. מבנה שנכון היום צריך
 * מנגנון שיישאר נכון גם אחרי שמישהו "רק יוסיף שדה כדי שהמסך ייטען מהר".
 */
export interface DailyListDoc {
  /** `yyyy-mm-dd` בשעון ישראל. */
  id: string;
  /** מזהי ההזמנות ברשימה של אותו יום. **מצביעים, לא תוכן.** */
  orderIds: string[];
  builtAt: string;
  /** נגזר מ-`orders`, לא מהמסמך הזה. קיים כדי שהמסך יידע אם צריך לבנות מחדש. */
  purgeAfter: string;
}
