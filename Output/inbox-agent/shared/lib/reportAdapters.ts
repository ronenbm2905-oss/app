import type { SettlementReport, SettlementSource } from './settlement';
import type { SheetGrid } from './xlsx';
import { tranzilaAdapter } from './adapters/tranzila';
import { gammaAdapter } from './adapters/gamma';

export interface ReportAdapter {
  /** מזהה פנימי יציב, לשימוש בקוד ובמבחנים. לא מוצג למשתמשת. */
  readonly id: string;
  /** איזה מהשניים זה. **האדפטר קובע, ולא אזור הגרירה שאליו היא שמה אותו.** */
  readonly source: SettlementSource;
  /** השם שהמשתמשת רואה. */
  readonly sourceHe: string;
  /**
   * האם הגיליון הזה שייך לאדפטר. **חתימה על צירוף כותרות** — ראו ההסבר
   * בראש הקובץ.
   */
  detect(grid: SheetGrid): boolean;
  /** הפרסור עצמו. שורה בעייתית אינה חריגה — היא יוצאת ל-`unreadableRows`. */
  parse(grid: SheetGrid): SettlementReport;
}

/**
 * ★ שני אדפטרים, ושניהם נמדדו מול קובץ אמיתי לפני שנכתבו.
 * הוספת שלישי בלי קובץ אמיתי היא חזרה על התקלה שנלמדה.
 */
export const ADAPTERS: readonly ReportAdapter[] = [tranzilaAdapter, gammaAdapter];

/**
 * האדפטר הראשון שמזהה את הגיליון, או `null`.
 *
 * ★ הראשון ולא "הטוב ביותר": ניקוד בין אדפטרים היה מכניס הכרעה מעורפלת
 * למקום שבו ההכרעה חייבת להיות ודאית. שני אדפטרים שמזהים אותו קובץ הם באג
 * באדפטרים, ו-`countDetections` קיים כדי שמבחן יתפוס אותו.
 */
export function detectAdapter(
  grid: SheetGrid,
  adapters: readonly ReportAdapter[] = ADAPTERS,
): ReportAdapter | null {
  for (const adapter of adapters) {
    if (adapter.detect(grid)) return adapter;
  }
  return null;
}

/** כמה אדפטרים מזהים את הגיליון. יותר מאחד = באג, ולא בחירה. */
export function countDetections(
  grid: SheetGrid,
  adapters: readonly ReportAdapter[] = ADAPTERS,
): number {
  return adapters.filter((adapter) => adapter.detect(grid)).length;
}
