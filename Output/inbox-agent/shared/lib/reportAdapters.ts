// לכן: האדפטר מקבל **גיליון מפורסר** (`SheetGrid`). פענוח הקובץ עצמו יושב
// ב-`xlsx.ts`, פעם אחת, ואדפטר עוסק רק בשאלה "אילו עמודות, ומה הן אומרות".
