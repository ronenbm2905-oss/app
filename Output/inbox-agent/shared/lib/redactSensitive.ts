// הגרסה הראשונה של התוכנית דרסה את `summaryHe` בלבד, בתוך שכבת המודל. סקירת
// עדי מצאה שם חור: `subject` נשמר גולמי, וכותרת מייל היא המקום שבו מידע רגיש
// מנוסח **הכי** מפורש — "תוצאות בדיקות", "זימון לדיון" — והיא יושבת לצד
// `fromAddress` שאומר על מי מדובר. ההגנה כיסתה את השדה הפחות חשוף מהשניים.
//
// לכן הדריסה יושבת ברמת הפריט הנשמר: היא רואה את `subject` ואת `summaryHe`
// יחד, ומכסה את שניהם.
//
// ---------------------------------------------------------------------------
// ★ כתיבה אחת, אחרי הוולידציה
// ---------------------------------------------------------------------------
// זו לא הערת סגנון אלא התנאי שבלעדיו כל השאר חסר ערך: **אסור שהצינור יכתוב
// את הכותרת לאחסון בשלב הסינון.** אם שלב 1 כותב פריט "מינימלי" עם `subject`
// ואז שלב 3 מעדכן אותו, הכותרת הגולמית כבר נחתה על הדיסק לפני שהמודל בכלל
// רץ — והדריסה מאחרת בכמה שניות ובכל הרשומות שכבר נכתבו. הפריט נבנה פעם אחת,
// אחרי שידוע `containsSensitive`, ורק אז נכתב.
//
// המשתמשת לא מאבדת דבר: היא רואה שיש פנייה, מתי, ומאיזה דומיין. התוכן נשאר
// איפה שהוא ממילא — ב-Gmail, אצל הבעלים שלו.
// ============================================================================

import type { ClassifiedItem, TriageItem } from '../types/triage';

/** מחליף את הכותרת. גנרי לחלוטין — אין בו רמז לנושא. */
export const SENSITIVE_SUBJECT_PLACEHOLDER = 'פנייה בנושא רגיש';

/** מחליף את הסיכום, ומפנה את המשתמשת למקור. */
export const SENSITIVE_SUMMARY_PLACEHOLDER = 'פנייה בנושא רגיש — פתח/י את המייל';

/**
 * דורס `subject` **וגם** `summaryHe` כשהמודל סימן `containsSensitive`.
 *
 * מוחזר פריט חדש; הפריט המקורי אינו משתנה. הקריאה חייבת להיות הצעד האחרון
 * לפני הכתיבה — ראה ההערה בראש הקובץ.
 */
export function redactSensitive(item: TriageItem): TriageItem {
  // פריט רעש אינו נושא `subject` ולא `agent` מלכתחילה — אין בו מה לדרוס.
  if (item.verdict === 'noise') return item;
  if (!item.agent?.containsSensitive) return item;

  const redacted: ClassifiedItem = {
    ...item,
    subject: SENSITIVE_SUBJECT_PLACEHOLDER,
    agent: {
      ...item.agent,
      summaryHe: SENSITIVE_SUMMARY_PLACEHOLDER,
      // כותרת משימה מוצעת היא ניסוח חופשי של אותו תוכן, ולכן היא נופלת תחת
      // אותה דריסה. משימה בשם "לחזור בנוגע לתוצאות הבדיקה" מדליפה בדיוק את
      // מה שהדריסה נועדה למנוע — ומדליפה אותו גם ללוח המשימות וגם ליומן.
      suggestedTaskTitle: null,
      suggestedDueDate: null,
    },
  };
  return redacted;
}
