// למה זה קובץ נפרד, ולא נשאר ב-`triageFilter`
// ---------------------------------------------------------------------------
// `triageFilter` צריך לדעת אם הודעה היא הודעת הזמנה (המסלול `order`), ו-
// `orderParse` צריך לנרמל כתובת כדי לענות על זה. שתי התלויות יחד הן מעגל.
//
// אפשר היה "לפתור" את זה בשכפול שלוש שורות הנרמול, וזה היה הפתרון הגרוע:
// שתי גרסאות של נרמול כתובת פירושן ששולח שנחשב זהה במקום אחד נחשב שונה
// במקום אחר — והמקום השני כאן הוא **אימות שולח של הזמנה**. פונקציה משותפת
// אחת, בשכבה שאין לה תלויות, היא הדרך היחידה שבה שתי הבדיקות לא יתפצלו.
//
// `triageFilter` ממשיך לייצא את שתיהן מחדש, כדי ששום קורא קיים לא ישבר.
