/**
 * `"דנה כהן" <Dana@Example.CO.IL>` → `dana@example.co.il`.
 * הכול עובר דרך כאן, אחרת השוואה מול רשימת הנמענים מחמיצה בגלל אות גדולה.
 *
 * ★ לקיחת מה שבתוך `<>` היא גם בקרת אבטחה ולא רק ניקוי: `"pay@tranzila.com"
 * <attacker@evil.example>` נראה לעין כמו כתובת הסליקה, ומה שחוזר מכאן הוא
 * הכתובת האמיתית. ראה `isOrderSender` ב-`orderParse.ts`.
 */
export function normalizeAddress(raw: string | null | undefined): string {
  const s = String(raw ?? '').trim();
  if (!s) return '';
  // הכתובת האחרונה בסוגריים משולשים, אם יש. `<>` הן הצורה הקנונית ב-RFC 5322.
  const angled = /<([^<>]+)>\s*$/.exec(s);
  return (angled ? angled[1] : s).trim().toLowerCase();
}

/** החלק שאחרי ה-`@`, מנורמל. מחרוזת ריקה אם אין. */
export function domainOf(address: string | null | undefined): string {
  const norm = normalizeAddress(address);
  const at = norm.lastIndexOf('@');
  return at === -1 ? '' : norm.slice(at + 1);
}
