import type { TenantScoped, Timestamped } from './tenant';
import type { Verdict } from './triage';

/**
 * ★ מקורות לגיטימיים לפסק דין בפנקס. **שניים, וזהו.**
 * הרחבת ה-union הזה היא הדרך היחידה לתת למודל השפעה על ארכוב — ולכן היא
 * צריכה להיראות כמו מה שהיא: שינוי בטיפוס שנמצא בקובץ עם ההערה הזאת.
 */
export type SenderVerdictSource = 'header' | 'user';

interface SenderLedgerFields extends Timestamped {
  /** `users/{uid}/senders/{domainKey}` — הדומיין המנורמל הוא המזהה. */
  domainKey: string;

  /**
   * פסק דין ברירת-מחדל לדומיין, שנצבר אוטומטית מהתנהגות.
   * `unknown` = ראינו אותו אבל אין הכרעה.
   */
  defaultVerdict: Verdict;

  /**
   * ★ דומיין של כלי-שיתוף (Drive / Dropbox / Calendly / חתימה דיגיטלית).
   *
   * זו התובנה השנייה של מאיה, מתורגמת לקוד: התראת Dropbox היא בוט — יש לה
   * `List-Unsubscribe`, היא מגיעה מ-`no-reply@`, וכל מסנן "האם השולח בוט"
   * היה קובר אותה. אבל **מאחוריה אדם שערך קובץ**. הגבול הנכון אינו "בוט או
   * אדם" אלא "האם יש מאחוריו אדם ועניין פתוח".
   *
   * הדגל אינו מקדם ל-`signal` — הוא רק אוסר על ירידה אוטומטית ל-`noise`.
   */
  neverAutoNoise: boolean;

  /**
   * ★ נוסף בפרוסה 0.5: מהדומיין הזה כבר הגיעו חשבוניות.
   *
   * נלמד מהתנהגות ולא מקודד קשיח, בדיוק כמו `defaultVerdict` — רשימת ספקים
   * קבועה בקוד הייתה נכונה ליום שנכתבה בלבד.
   *
   * שים לב לצירוף שנראה סותר ואינו: דומיין יכול להיות `defaultVerdict: 'noise'`
   * **וגם** `invoiceSource: true`. זה המצב הרגיל ולא החריג — חשבונית ספק
   * מגיעה מ-`billing@` עם `List-Unsubscribe`, כלומר המסנן קובע עליה רעש
   * בצדק. הדגל הזה הוא מה שמונע ממנה בכל זאת להיארכב: ראה כלל 5 ב-
   * `archivePolicy.ts`.
   */
  invoiceSource: boolean;

  /**
   * ★ **מאיפה הגיע פסק הדין הזה.** הוספה שנובעת מסקירת עדי, והיא סותמת חור
   * אמיתי שלא ראיתי.
   *
   * הכלל "רק המסנן הדטרמיניסטי מארכב, לא המודל" נשמע הרמטי — אבל **המסנן
   * קורא את הפנקס**. כלומר אם משהו במורד הזרם יכול לכתוב לפנקס על סמך פלט
   * מודל, המודל משפיע על ארכוב דרך הדלת האחורית, והכלל דולף מבפנים בלי
   * שאף מבחן על `triageFilter` יבחין.
   *
   * לכן שני מקורות בלבד, ו**אין שלישי**:
   *   `'header'` — ראיה בכותרות RFC (`List-Unsubscribe`, `Precedence`).
   *   `'user'`   — בעלת העסק אמרה במפורש.
   *
   * אין `'auto'` ואין `'model'`. הכתיבה עוברת דרך `shared/lib/senderLedger.ts`
   * בלבד, והטיפוס הזה הוא מה שהופך את זה לשגיאת קומפילציה ולא לנוהג.
   */
  verdictSource: SenderVerdictSource;

  messageCount: number;
  /** כמה פעמים המשתמשת השיבה לדומיין הזה. אות חזק לסיגנל. */
  repliedCount: number;
  lastSeenAt: string;
}

export type SenderLedgerEntry = TenantScoped<SenderLedgerFields>;

/**
 * הוראת משתמש מפורשת — עוקפת הכול, כולל את הפנקס האוטומטי.
 * `scope: 'address'` גובר על `scope: 'domain'`; הספציפי מנצח את הכללי.
 */
export interface UserSenderRule {
  scope: 'address' | 'domain';
  /** כתובת מנורמלת או `domainKey`. */
  value: string;
  verdict: Verdict;
  note?: string;
}
