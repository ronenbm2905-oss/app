/**
 * שני מצבים בלבד, ו**סימון ידני** בין השניים.
 *
 * זו הכרעה של רונן ולא קיצור דרך: המערכת לא יודעת מתי חבילה יצאה בפועל, ואין
 * לה שום דרך לדעת. מצב שלישי מסוג "בטיפול" או "נארז" נשמע מועיל ומייצר מיד
 * שאלה שאין לה תשובה — מתי בדיוק הוא נגמר. שתי אפשרויות שהמשתמשת שולטת בהן
 * לגמרי עדיפות על ארבע שהמערכת מנחשת.
 */
export type OrderStatus = 'new' | 'shipped';

// ---------------------------------------------------------------------------
// ★ הרשומה
// ---------------------------------------------------------------------------

interface OrderRecordFields extends Timestamped {
  /** `ord-<messageId>`. */
  id: string;
  /** ההודעה שממנה נקראה. הקישור "למקור" שהמסך מציג. */
  sourceMessageId: string;
  threadId: string;
  fromDomain: string;
  /** מתי ההודעה התקבלה — וגם התאריך שנשאר אחרי המחיקה. */
  receivedAt: string;

  recipient: OrderRecipient;
  items: OrderItem[];

  /** `סכום ששולם` — הסכום **הכולל**. עצמאי, ולא נגזר מהשורות. */
  paidTotal: number | null;
  /** מטבע כפי שנקרא מההודעה. לא מונח מראש. */
  currency: string | null;
  /** `תשלומים`. 1 = תשלום אחד. */
  installments: number | null;

  status: OrderStatus;
  /** ISO. `null` כל עוד לא סומנה כנשלחה. */
  shippedAt: string | null;

  /**
   * ★★ מתי פרטי הנמענת נמחקים. **תמיד יש תאריך.**
   *
   * הניסוח הראשון של המדיניות היה "כל עוד ההזמנה לא יצאה — הכול נשמר", בלי
   * תאריך כלל. סקירת עדי הפילה אותו בשורה אחת: פירושו ש**הזמנה שאף אחד לא
   * סימן מחזיקה כתובת מגורים לנצח**, כלומר כל סכימת המחיקה תלויה בכך שאדם
   * יזכור ללחוץ על צ׳קבוקס. בקרה שתלויה בזיכרון של אדם עסוק אינה בקרה.
   *
   * לכן שני שעונים, והמוקדם שבהם קובע:
   *   `shippedAt + 60`      — המסלול הרגיל, אחרי שהחבילה יצאה.
   *   `receivedAt + 180`    — ★ **רצפה מוחלטת**, בלי קשר לסטטוס.
   *
   * `null` נשאר אפשרי רק למקרה של `receivedAt` פגום — כלומר תקלה, לא מדיניות.
   */
  purgeAfter: string | null;

  /**
   * ★ `true` אחרי שפרטי הנמענת נמחקו.
   *
   * השדה נשאר גם אחרי המחיקה, וזו כל הנקודה: רשומה עם שדות ריקים ובלי הדגל
   * נראית בדיוק כמו הזמנה שלא הצלחנו לקרוא. עם הדגל, המסך אומר "נמחק לפי
   * המדיניות" במקום "לא הצלחתי לקרוא" — שני מצבים הפוכים לגמרי.
   */
  recipientPurged: boolean;

  needsHumanReview: boolean;
  issues: OrderIssue[];
}

export type Order = TenantScoped<OrderRecordFields>;

// ---------------------------------------------------------------------------
// עזרים טהורים על הרשומה
// ---------------------------------------------------------------------------

/** ★ מה שבאמת נכנס לחבילה. השורות במחיר 0 יורדות כאן, במקום אחד. */
export function packableItems(order: Pick<Order, 'items'>): OrderItem[] {
  return order.items.filter((i) => i.isPackable);
}

/** סך היחידות לאריזה. זה המספר שצריך להיות הגדול ביותר על המסך. */
export function totalUnitsToPack(order: Pick<Order, 'items'>): number {
  return packableItems(order).reduce((sum, i) => sum + i.quantity, 0);
}

/** האם יש בכלל מה לארוז. `false` הוא מצב חריג שדורש עין. */
export function hasSomethingToPack(order: Pick<Order, 'items'>): boolean {
  return packableItems(order).length > 0;
}

/**
 * הכתובת כטקסט אחד, בשורות — בדיוק מה שנכנס ללוח ההעתקה.
 *
 * פונקציה אחת ולא בנייה בתוך הרכיב, כי הטקסט הזה מגיע לחבילה אמיתית: אם
 * המסך יבנה אותו לבד, שינוי בסדר השדות במסך אחד לא יגיע לשני.
 */
export function formatAddressBlock(r: OrderRecipient): string {
  const cityLine = [r.city, r.postalCode].filter(Boolean).join(' ');
  return [r.name, r.street, cityLine, r.phone]
    .map((v) => (v ?? '').trim())
    .filter(Boolean)
    .join('\n');
}
