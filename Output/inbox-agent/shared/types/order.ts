// ============================================================================
// order.ts — הזמנה שמגיעה כהודעה אוטומטית ממערכת הסליקה.
//
// ---------------------------------------------------------------------------
// ★ מה שונה כאן מכל שאר המערכת
// ---------------------------------------------------------------------------
// עד עכשיו הכלל היה "מחזיקים מצביעים ונגזרות, לא תוכן". בהזמנה זה נשבר,
// ובכוונה: **הכתובת אינה תופעת לוואי של הפיצ׳ר, היא הפיצ׳ר.** בלי שם, רחוב,
// עיר ומיקוד אי אפשר לשלוח חבילה, ולכן "לא לאסוף" אינו מזעור אלא ביטול
// המוצר.
//
// המזעור עובר למקום אחר לגמרי — **לזמן**. כל עוד ההזמנה לא יצאה, הכול נשמר;
// מרגע שהיא סומנה כנשלחה מתחיל שעון, ובסופו פרטי הנמענת נמחקים ונשארת רשומה
// מצומצמת. ההיגיון והמזעור מסכימים כאן זה עם זה: אחרי שהחבילה הגיעה, הכתובת
// כבר לא משרתת שום דבר — היא רק מצטברת. ראה `shared/lib/orderRetention.ts`.
//
// זה קריטי בקנה מידה: כל לקוחה חדשה בחנות היא נושא מידע נוסף, ובחנות שמוכרת
// מוצר פיזי הקצב הזה לא נעצר.
//
// ---------------------------------------------------------------------------
// ★ שלוש המלכודות שנמצאו בהזמנות אמיתיות, ואיפה כל אחת יושבת בטיפוסים
// ---------------------------------------------------------------------------
//  1. **שורת מוצר במחיר 0 שאינה פריט לארוז** — למשל שורת הטבת משלוח שמופיעה
//     בכל הזמנה עם כמות 1 ומחיר 0. פרסר תמים יגיד לארוז אותה. → `isPackable`
//     על כל שורה, וכלל מפורש ב-`orderParse` עם מבחן ייעודי.
//
//  2. **הכמות משתנה בין הזמנות.** נראו 1 ו-4 של אותו מוצר. לשלוח 1 במקום 4
//     היא הטעות היקרה כאן — היא עולה משלוח נוסף, התנצלות, ולקוחה שממתינה
//     שבוע נוסף. → `quantity` הוא **מספר שלם מאומת**, ו-`null` אינו אפשרות:
//     שורה שלא הצלחנו לקרוא ממנה כמות **פוסלת את כל ההזמנה** לבדיקה, במקום
//     להיכנס לרשימת האריזה עם ניחוש.
//
//  3. **`סכום ששולם` הוא הסכום הכולל, ו`מחיר ליחידה` נפרד.** אין להסיק אחד
//     מהשני. → `paidTotal` הוא שדה עצמאי, והמכפלה **מאומתת** מולו.
// ---------------------------------------------------------------------------

import type { TenantScoped, Timestamped } from './tenant';

// ---------------------------------------------------------------------------
// הנמענת
// ---------------------------------------------------------------------------

/**
 * מי מקבלת את החבילה, ולאן.
 *
 * כל השדות `| null` מאותו טעם שבחשבוניות: **ערך שחולץ ולא אומת גרוע מערך
 * חסר.** כתובת חלקית שנראית שלמה גורמת לחבילה לצאת למקום הלא נכון; שדה ריק
 * עם הסבר גורם לבעלת העסק לפתוח את המייל.
 *
 * מה שאין כאן, ובכוונה: אין שדה חופשי, אין הערות, ואין שום דבר שקשור לאמצעי
 * התשלום — לא מספר כרטיס ולא ארבע ספרות אחרונות. הודעת הסליקה מכילה יותר
 * ממה שרשום כאן; הרשימה הזאת היא **מה שצריך כדי לכתוב על חבילה**, וכל מה
 * שמעבר לה לא נשמר. שדה שאף אחד לא צריך הוא שדה שאף אחד לא ישים לב שהוא
 * נשמר.
 */
export interface OrderRecipient {
  name: string | null;
  phone: string | null;
  email: string | null;
  street: string | null;
  city: string | null;
  postalCode: string | null;
  /** קוד מדינה דו-אותיות, כפי שהופיע בהודעה. */
  countryCode: string | null;
}

export const EMPTY_RECIPIENT: OrderRecipient = {
  name: null,
  phone: null,
  email: null,
  street: null,
  city: null,
  postalCode: null,
  countryCode: null,
};

/**
 * ★ נעילת רשימת השדות, באותה תבנית כמו `ALLOWED_INVOICE_FIELDS`.
 * המבחן משווה מולה את מפתחות `OrderRecipient` בפועל, כך שהוספת שדה מפילה
 * מבחן ומחייבת החלטה מודעת. זה הרכיב שמונע מ"רק נשמור גם את זה" לקרות בשקט.
 */
export const ALLOWED_RECIPIENT_FIELDS = [
  'name',
  'phone',
  'email',
  'street',
  'city',
  'postalCode',
  'countryCode',
] as const;

// ---------------------------------------------------------------------------
// שורת מוצר
// ---------------------------------------------------------------------------

/**
 * שורה אחת מטבלת המוצרים.
 *
 * ★ `isPackable` הוא הלב. ראה מלכודת 1 בראש הקובץ: שורה במחיר 0 היא כמעט
 * תמיד הטבה, זיכוי או ציון משלוח — **לא חפץ שנכנס למעטפה**. היא נשמרת
 * ברשומה, כי היא חלק ממה שהלקוחה קנתה ומההסבר לסכום, אבל היא לא מופיעה
 * ברשימת האריזה.
 *
 * הבחירה בשדה מפורש ולא בסינון בזמן תצוגה מכוונת: סינון בתצוגה חוזר על עצמו
 * בכל מסך, ומספיק שמסך אחד ישכח.
 */
export interface OrderItem {
  productName: string;
  /** מספר שלם חיובי. שורה שלא נקראה ממנה כמות פוסלת את ההזמנה כולה. */
  quantity: number;
  unitPrice: number;
  /** נגזר: `unitPrice > 0`. ראה ההערה למעלה. */
  isPackable: boolean;
  /** `quantity * unitPrice`. מחושב כאן, לא נקרא מההודעה. */
  lineTotal: number;
}

// ---------------------------------------------------------------------------
// ממצאים
// ---------------------------------------------------------------------------

export type OrderIssueCode =
  // --- אימות מקור. שלושתם חוסמים. ---
  | 'senderMismatch' // לא מכתובת הסליקה
  | 'subjectMismatch' // לא הנושא הקבוע
  | 'dkimMissing' // אין חתימת שולח לבדוק
  | 'dkimFail' // החתימה לא נכונה או לא של ספק הסליקה
  | 'structureMismatch' // המבנה אינו המבנה המוכר
  // --- תוכן ---
  | 'missingField'
  | 'quantityUnreadable'
  | 'priceUnreadable'
  | 'noItems'
  | 'noPackableItems' // ★ כל השורות במחיר 0 — אין מה לארוז
  | 'totalMismatch' // ★ המכפלה לא מסתדרת מול הסכום ששולם
  | 'suspiciousValue' // קישור או טקסט זר בתוך שדה כתובת
  | 'invisibleChars' // ★ תווי כיווניות/רוחב-אפס בשדה שהוקלד בידי אדם
  | 'fieldTooLong'
  | 'malformedCountry'
  | 'malformedPostalCode';

/**
 * `block` — ההזמנה מסומנת לבדיקה, **ואין ממנה כתובת להעתקה**.
 * `warn` — ההזמנה עובדת כרגיל, עם הערה גלויה על הכרטיס.
 *
 * ההבחנה נדרשת כי אין טעם לחסום הזמנה שלמה בגלל מיקוד בפורמט מוזר, ואין שום
 * טעם לאפשר אריזה של הזמנה שהמספרים בה לא מסתדרים.
 */
export type OrderIssueSeverity = 'block' | 'warn';

export interface OrderIssue {
  field: keyof OrderRecipient | 'source' | 'items' | 'total' | 'document';
  code: OrderIssueCode;
  severity: OrderIssueSeverity;
  /** ★ מנוסח לבעלת העסק. "לא הצלחתי לקרוא כמה יחידות", לא קוד שגיאה. */
  messageHe: string;
}

