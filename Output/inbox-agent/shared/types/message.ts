// למה זה קובץ נפרד, ולמה דווקא עכשיו
// ---------------------------------------------------------------------------
// הטיפוס הזה ישב עד עכשיו ב-`triage.ts`, לצד `TriageDecision`, `AgentOutput`
// ו-`needsLlm`. כשהצטמצם המוצר למודול ההזמנות בלבד, כל הקובץ ההוא עבר
// ל-`frozen/` — **אבל `MessageMeta` הוא לא חלק ממסלול המודל.** הוא מתאר מה
// חוזר מ-`messages.get(format:'metadata')`: מי שלח, מתי, ומה בכותרות. בלעדיו
// אי אפשר לזהות הודעת סליקה בכלל.
//
// שתי החלופות היו גרועות יותר: להשאיר את `triage.ts` בבנייה בגלל טיפוס אחד
// (כלומר לגרור איתו את `AgentOutput`), או לשכפל את המבנה — ואז אותה הודעה
// מתוארת בשני מקומות שיסטו זה מזה. `frozen/types/triage.ts` מייבא מכאן,
// ולכן יש הגדרה אחת.
// ============================================================================

export interface MessageMeta {
  /**
   * ★★ המזהה של **המקור** (ב-Gmail: `id`), ולא כותרת `Message-ID` של ההודעה.
   *
   * ההבחנה קריטית ולא פורמלית: `Message-ID` הוא כותרת שהשולח כותב, והיא
   * **אינה נכללת ב-`h=`** של חתימת ספק הסליקה — כלומר אפשר לשנות אותה
   * בהודעה אמיתית וחתומה ולשלוח שוב. `id` של Gmail מוקצה על ידי Gmail
   * בקליטה, ואיש מבחוץ אינו קובע אותו.
   *
   * ולכן גם: זיהוי כפילות **לא** נשען על השדה הזה לבדו. ראה
   * `markDuplicates` ב-`orderPipeline.ts` ואת `fingerprint.ts`.
   */
  messageId: string;
  threadId: string;
  /** כתובת השולח בלבד (בלי שם התצוגה). מנורמלת ב-`normalizeAddress`. */
  fromAddress: string;
  /** שם התצוגה של השולח, אם היה. מוצג — לא משמש לסינון (קל לזייף). */
  fromName?: string;
  subject: string;
  /**
   * ★★ **זמן הקליטה אצלנו** (ב-Gmail: `internalDate`), ב-ISO 8601.
   * **לא** כותרת `Date` של ההודעה.
   *
   * הסיבה זהה: `h=` של ספק הסליקה מכסה `Received:From:To:Subject` בלבד,
   * כלומר `Date` ניתן לשינוי בהודעה חתומה בלי לשבור את החתימה. מי שימלא
   * את השדה הזה מהכותרת יאפשר לזר לקבוע מה "הישן ביותר" ברשימת האריזה,
   * ומתי הזמנה נמחקת לפי מדיניות השמירה — שני דברים שנגזרים ממנו.
   *
   * זמן הקליטה נקבע על ידי השרת שקיבל את ההודעה, ולכן הוא הדבר היחיד כאן
   * שאף אחד מבחוץ אינו כותב.
   */
  receivedAt: string;

  // כותרות RFC שמסגירות דיוור המוני. כולן אופציונליות — היעדרן הוא מידע.
  replyTo?: string | null;
  listUnsubscribe?: string | null;
  /** `bulk` / `list` / `junk` — RFC 2076. */
  precedence?: string | null;
  /** `auto-generated` / `auto-replied` — RFC 3834. */
  autoSubmitted?: string | null;
}
