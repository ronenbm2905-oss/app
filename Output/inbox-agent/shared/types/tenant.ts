// ============================================================================
// tenant.ts — בידוד דיירים (multi-tenancy) ברמת הטיפוס.
//
// למה טיפוס ולא הערה: `TenantScoped<T>` הופך את "כל מסמך נושא userId" מהצהרה
// בתיעוד לדבר שהקומפיילר אוכף. מסמך שנבנה בלי `userId` פשוט לא עובר build.
//
// המסמכים ממילא יושבים תחת `users/{uid}/...` (כלל בידוד אחד שאי אפשר לשכוח),
// אבל השדה הכפול נדרש ל-`collectionGroup` מה-Admin SDK — שאילתה חוצת-משתמשים
// חייבת לסנן על שדה, כי הנתיב לבדו אינו זמין לה כתנאי.
//
// פרוסה 0 מקומית לחלוטין (אין Firestore), ובכל זאת הטיפוסים נבנים נכון מהיום
// הראשון: להוסיף בידוד בדיעבד פירושו לעבור על כל מסמך שכבר נכתב.
// ============================================================================

/** מזהה משתמש (Firebase Auth uid). בפרוסה 0 קבוע — ראה `constants.ts`. */
export type UserId = string;

/**
 * כל ישות שנשמרת שייכת למשתמש אחד ויחיד.
 * `readonly` בכוונה: `userId` לא משתנה אחרי יצירה — שינוי כזה הוא העברת בעלות
 * על מידע, לא עדכון שדה, והוא צריך להיראות כשגיאת קומפילציה.
 */
export type TenantScoped<T> = T & { readonly userId: UserId };

/** חותמות זמן — ISO 8601 מחרוזתי, כדי שיהיה זהה ב-localStorage וב-Firestore. */
export interface Timestamped {
  createdAt: string;
  updatedAt: string;
}

/**
 * `purgeAfter` — תאריך ISO שאחריו הרשומה נמחקת מחיקה קשה.
 *
 * השדה קיים כאן ולא ב"מתישהו": ההערה ב-
 * `Output/hachzarei-mas/functions/src/index.ts` מתעדת בדיוק את הכשל ההפוך —
 * `purgeAfter` נכתב ואף אחד לא קרא אותו, כלומר המדיניות הצהירה על מחיקה
 * שלא קרתה. בפרוסה 0 המחיקה מתבצעת בטעינה (ראה `pipeline.ts`).
 */
export interface Expirable {
  purgeAfter: string;
}
