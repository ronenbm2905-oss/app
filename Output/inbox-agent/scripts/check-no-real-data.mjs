// ============================================================================
// check-no-real-data.mjs — ★★ השער העשירי: **אין בריפו נתון מהקובץ האמיתי.**
//
// ---------------------------------------------------------------------------
// מה קרה, ולמה נדרש שער ולא זהירות
// ---------------------------------------------------------------------------
// כשנבנו האדפטרים, מספרי השידור והסכומים מהקובץ האמיתי של בעלת העסק הודבקו
// לתוך ה-fixtures. זה לא קרה מחוסר תשומת לב: ת.ז ומספרי כרטיס **כן** סוננו,
// כי הם סומנו כרגיש. מספרי אצווה של סליקה לא סומנו — ולכן עברו.
//
// זה בדיוק הכשל שחוזר בפרויקט הזה: **הגנה שנשענת על מי שזוכר לסמן.** הריפו
// הזה ציבורי והוא מזהה את העסק בשמו, ומספרי אצווה + סכומים הם מחזור אמיתי.
//
// ---------------------------------------------------------------------------
// ★★ ולמה **רשימה מותרת**, ולא רשימה אסורה
// ---------------------------------------------------------------------------
// הדרך המתבקשת היא רשימה שחורה: לכתוב כאן את ששת מספרי השידור האמיתיים
// ולהפיל את הבנייה עליהם. **זו הדרך הלא נכונה, משתי סיבות:**
//
//  1. ⛔ **היא מפרסמת בדיוק את מה שהיא מגנה עליו.** הריפו ציבורי; הרשימה
//     האסורה תישב בו בטקסט גלוי. גם גיבוב לא עוזר — שמונה ספרות עם מלח
//     ידוע נשברות במלואן בשניות.
//  2. היא מגינה רק על **ששת הערכים שכבר ראינו**. הקובץ הבא יביא ששה אחרים,
//     ואף אחד לא יזכור לעדכן.
//
// לכן ההיפוך, ובאותו עיקרון שכבר כתוב ב-`check-dist.mjs`: *"לא האם יש קריאת
// רשת אלא **לאן** היא יכולה ללכת ... רשימה סגורה"*. השאלה כאן אינה
// *"האם זה מספר אמיתי"* — אי אפשר לדעת — אלא **"האם הוא רשום כמומצא"**.
//
// כל רצף של 7 ספרות ומעלה בקבצים שנסרקים חייב להופיע ב-`ALLOWED_DIGITS`.
// מספר אמיתי שיודבק מחר — כל מספר אמיתי, לא רק אלה שראינו — יפיל את הבנייה,
// ואף ערך אמיתי אינו נכתב כאן.
//
// ---------------------------------------------------------------------------
// למה 7 ספרות
// ---------------------------------------------------------------------------
// מספרי השידור שנמדדו הם בני שמונה ספרות. הסף 7 נותן מרווח כלפי מטה בלי
// לתפוס תאריכים (\`2026-08-04\`), סכומים באגורות (\`73_000\`) או קודי סירוב.
// מספרים ארוכים בקוד כתובים ממילא עם קו תחתון (\`86_400_000\`) — סגנון
// שקיים בפרויקט מלכתחילה, והוא גם מה שמונע מהם להיתפס כאן.
//
// ⚠️ מה שהשער **לא** תופס: סכומים. 310 ו-420 אינם ניתנים להבחנה מכל סכום
// אחר במבחן, ורשימה אסורה עליהם הייתה חוזרת לשתי הבעיות שלמעלה. הם הוחלפו
// ידנית, והטענה עליהם צרה יותר: **סכום בלי מספר האצווה שלצדו אינו מזהה.**
// ============================================================================

import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/**
 * הקבצים שנסרקים: כל מה שנוגע בקבצים של בעלת העסק, ובראשם ה-fixtures.
 *
 * ★ רשימה מפורשת ולא תיקייה שלמה, מאותו טעם כמו בשאר השערים: קובץ שנמחק
 * או שהשם שלו השתנה הוא **כשל**, ולא "פחות קבצים לסרוק".
 */
export const WATCHED_FILES = [
  'shared/lib/settlement.ts',
  'shared/lib/settlementGroup.ts',
  'shared/lib/reconcile.ts',
  'shared/lib/reconcileCsv.ts',
  'shared/lib/reportAdapters.ts',
  'shared/lib/xlsx.ts',
  'shared/lib/adapters/tranzila.ts',
  'shared/lib/adapters/gamma.ts',
  'src/components/ReconcileView.tsx',
  'tests/fixtures/xlsxBuilder.ts',
  'tests/settlementAdapters.test.ts',
  'tests/settlementGroup.test.ts',
  'tests/reconcileUpload.test.tsx',
  'tests/reconcileScreen.test.tsx',
  'tests/reconcileCsv.test.ts',
  'tests/reconcileNav.test.tsx',
  'tests/reconcile.test.ts',
  'tests/xlsxRead.test.ts',
];

/**
 * ★★ הרשימה המותרת. **כל ערך כאן מומצא**, וזה מה שמאפשר לכתוב אותו בגלוי.
 *
 * מוסיפים לכאן רק ערך שמישהו **המציא** — לא ערך שהועתק מקובץ. אם מספר
 * שהודבק מקובץ אמיתי מפיל את השער, התשובה היא להחליף אותו במספר מומצא,
 * **לא** לרשום אותו כאן.
 *
 * ★ מספרי השידור המומצאים נבחרו בטווח \`9000xxxx\` כדי שיהיה **ניכר מהמראה**
 * שהם לא מקובץ: שישה מתוכם רצופים, וכולם מתחילים באותו קידומת.
 */
export const ALLOWED_DIGITS = new Map([
  ['90000001', 'מספר שידור מומצא — שידור א׳ ב-fixtures'],
  ['90000002', 'מספר שידור מומצא — שידור ב׳ ב-fixtures'],
  ['90000003', 'מספר שידור מומצא — הקובץ עם סדר עמודות מהופך'],
  ['090000001', 'אותו שידור עם אפס מוביל — למבחן שהאפס אינו מוסר'],
  ['000000000', 'ת.ז מומצאת ב-fixture. קיימת בקובץ כדי שיהיה מה **לא** לקרוא'],
  ['1234567', 'מספר אישור / מספר מסוף מומצא'],
  ['12345678', 'מספר חשבון מומצא ב-fixture'],
  ['7654321', 'מספר אישור מומצא, בקובץ עם סדר עמודות מהופך'],
  ['0000000', 'מספר אישור של עסקה שנדחתה — אפסים, כמו בפורמט עצמו'],
]);

/** רצף ספרות שאורכו כאורך מספר שידור או יותר. */
const DIGIT_RUN = /\d{7,}/g;

/**
 * כל ההפרות. מקבלת רשימת קבצים כדי שהמבחן השלילי יוכל להריץ אותה על פיתיון.
 */
export function findRealDataViolations(files = WATCHED_FILES) {
  const violations = [];

  for (const rel of files) {
    const full = join(ROOT, rel);
    if (!existsSync(full)) {
      violations.push({
        file: rel,
        line: 0,
        value: '',
        why: 'קובץ שהשער אמור לסרוק אינו קיים — או שנמחק, או שהשם השתנה',
      });
      continue;
    }

    const lines = readFileSync(full, 'utf8').split('\n');
    lines.forEach((line, index) => {
      for (const match of line.matchAll(DIGIT_RUN)) {
        const value = match[0];
        if (ALLOWED_DIGITS.has(value)) continue;
        violations.push({
          file: rel,
          line: index + 1,
          value,
          why: 'רצף ספרות שאינו רשום כמומצא',
        });
      }
    });
  }

  return violations;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const violations = findRealDataViolations();
  if (violations.length > 0) {
    console.error('\n✖ נמצא בקוד מספר ארוך שאינו רשום כמומצא.\n');
    console.error('  הריפו הזה ציבורי והוא מזהה את העסק בשמו. מספר אצווה של');
    console.error('  סליקה שהודבק מקובץ אמיתי הוא נתון של לקוחה, גם אם הוא');
    console.error('  נראה כמו נתון דוגמה.\n');
    for (const v of violations) {
      console.error(`  ${v.file}${v.line ? ':' + v.line : ''}  ${v.value}  [${v.why}]`);
    }
    console.error('\n  אם הערך הועתק מקובץ — תחליפו אותו בערך מומצא.');
    console.error('  אם הוא נכתב מהראש — תוסיפו אותו ל-ALLOWED_DIGITS עם הסבר.');
    console.error('  ואם זה מספר טכני ארוך — קו תחתון (1_000_000) פותר את זה.\n');
    process.exit(1);
  }
  console.log(`✓ אין בקוד ההשוואה נתון מהקובץ האמיתי (${WATCHED_FILES.length} קבצים נסרקו).`);
}
