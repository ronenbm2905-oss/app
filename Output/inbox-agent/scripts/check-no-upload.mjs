// ============================================================================
// check-no-upload.mjs — ★★ השער שהופך את הבאנר שעל המסך לעובדה.
//
// ---------------------------------------------------------------------------
// מה כתוב על המסך, ולמה זה מחייב בדיקה
// ---------------------------------------------------------------------------
// במסך השוואת דוחות הגבייה כתוב, בבאנר קבוע:
//
//     "הקבצים נשארים במחשב שלך. שום דבר מהם לא נשלח לשום מקום ולא נשמר בכלי — כשסוגרים את החלון, זה נעלם."
//
// הדוחות האלה מכילים **פירוט עסקאות של צד שלישי**. ההכרעה מול המשתמש הייתה
// שהכול מעובד בדפדפן — לא Firestore, לא Storage, ולא אחסון מקומי — וזו בדיוק
// ההכרעה שמוציאה את הפיצ׳ר משער משפטי. כלומר: המשפט הזה אינו ניסוח מרגיע,
// הוא **התנאי** שעליו הפיצ׳ר עומד.
//
// ובפרויקט הזה כבר למדנו, שלוש פעמים, מה שווה הבטחה בלי בדיקה: כלל הארכוב
// "שלא אמור לרוץ" שכן היה יכול לרוץ, מסלול ההזמנות, ו-`purgeAfter` שנכתב
// ואיש לא קרא. הרף שנקבע אז תקף גם כאן: *"'הסרנו את הקוד' היא טענה על מה
// שנעשה"* — נדרשת בדיקה שמפילה build. זו היא.
//
// ---------------------------------------------------------------------------
// מה בדיוק נבדק
// ---------------------------------------------------------------------------
// הליכה על **גרף הייבוא** מארבע נקודות כניסה (`WATCHED_ENTRIES`) — המסך
// ושלושת מודולי הליבה — ואיסור על כל סימן של שליחה או שמירה בכל קובץ שמגיעים
// אליו. גרף ולא רשימת קבצים, מאותו טעם שכתוב ב-`buildGraph.mjs`: רשימה עונה
// על "מה שזכרנו לרשום", וגרף עונה על השאלה עצמה.
//
// שלושה דברים נוספים שהשער דורש, וכל אחד למה:
//
//  1. **ייבוא דינמי אסור.** זה הדבר היחיד שהליכה סטטית לא יכולה לעקוב
//     אחריו — ובלעדיו הגרף אינו הוכחה אלא הערכה.
//  2. **ייבוא שלא נפתר הוא כשל.** קובץ שלא מצאנו הוא קובץ שלא סרקנו.
//  3. **נקודת כניסה שנעלמה היא כשל.** אחרת מחיקת המסך הופכת את השער
//     לבדיקה שעוברת תמיד — הצורה השקטה ביותר שבה בקרה מתה.
//
// ---------------------------------------------------------------------------
// ⚠️ ומה שהשער **לא** אומר
// ---------------------------------------------------------------------------
// שאי אפשר להעתיק נתון מהמסך ביד, ושהדפדפן עצמו לא שומר כלום (היסטוריה,
// קובץ שהמשתמשת הורידה בעצמה). הוא אומר דבר צר ומדויק: **בקוד של הפיצ׳ר
// הזה אין נתיב ששולח או שומר.** זו הטענה שאפשר לעמוד מאחוריה.
//
// ---------------------------------------------------------------------------
// 🔴★★ ושתי אזהרות למי שיגיע לכאן כדי להרחיב
// ---------------------------------------------------------------------------
//
//  1. **השער הזה אינו מה שמחזיק את הפיצ׳ר מחוץ לשער המשפטי.** קל להניח
//     שכן — הוא הדבר שרואים, הוא רץ בכל build, והוא מגן על משפט שכתוב על
//     המסך. אבל הטענה הנושאת היא שב**פלט אין אדם**: אין שם, אין ת.ז, אין
//     כרטיס, אין IP. מי שיוסיף מחר עמודה שמינית לפרסר יראה את השער הזה
//     **ירוק**, כי הוא לא יודע מה יש בשורה — רק לאן היא הולכת. ההגנה
//     האמיתית היא `MinimizedFields` ומבחני הדליפה; ראו את ההערה המלאה
//     ב-`shared/lib/settlement.ts`.
//
//  2. **בורר קבצים פתוח ואפס שמירה הם זוג, ואסור להפריד ביניהם.** בבורר
//     כאן אין allowlist ואין מגבלת גודל: `accept=".xlsx"` הוא רמז ל-UI,
//     לא אכיפה. אפשר לגרור לשם קובץ שכר או טופס רפואי, והכלי יקרא אותו
//     לזיכרון לפני שיאמר "עוד לא מכירים את הפורמט". מה שהופך את זה
//     למקובל הוא **אך ורק** שכלום לא נשאר.
//
//     ⛔ כלומר: ברגע שמישהו יוסיף "לשמור את ההשוואה של חודש שעבר" — ולו
//     ב-`localStorage` — הבורר הפתוח הופך לבעיה באותה שנייה. והמקום שבו
//     יפתחו את החריג הזה הוא **בדיוק כאן**, ברשימת הסימנים האסורים. לכן
//     האזהרה יושבת כאן ולא במסמך: מי שיבוא להוסיף היסטוריה יעבור בקובץ
//     הזה בדרך, ויצטרך למחוק את הפסקה במודע.
//
// ★ ההוכחה שהשער עצמו עובד יושבת ב-`tests/noUploadPath.test.ts`: הוא מריץ
// אותו על קובץ פיתיון שמכיל כל אחד מהסימנים האסורים ודורש שייכשל. שער
// שלא הוכח שהוא תופס אינו שער.
// ============================================================================

import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { buildGraph, codeOf, ROOT } from './buildGraph.mjs';

/**
 * נקודות הכניסה. המסך, ושלושת המודולים שהוא בנוי מהם.
 *
 * ★ שלושת המודולים נבדקים **גם בנפרד** מהמסך, ולא רק דרכו: מחר מישהו יצרוך
 * את `reconcile.ts` ממקום אחר, וההבטחה צריכה להישאר נכונה על המודול עצמו.
 */
export const WATCHED_ENTRIES = [
  'src/components/ReconcileView.tsx',
  'shared/lib/reconcile.ts',
  'shared/lib/settlement.ts',
  'shared/lib/reportAdapters.ts',
  'shared/lib/settlementGroup.ts',
  'shared/lib/xlsx.ts',
];

/**
 * הסימנים האסורים, בשלוש משפחות.
 *
 * ★ כולם **שמות מזוהים** ולא מילים כלליות — אותו כלל כמו ב-`check-no-model`:
 * סימן שנדלק על טקסט תמים הוא סימן שיוסר מהרשימה בפעם הראשונה שיפריע.
 */
export const FORBIDDEN_MARKERS = [
  // ענן — שמירה אצלנו
  { marker: 'firebase/firestore', why: 'ענן: Firestore' },
  { marker: 'firebase/storage', why: 'ענן: Storage' },
  { marker: 'httpsCallable', why: 'ענן: קריאה לפונקציה בשרת' },
  // רשת — שליחה לאן שהוא
  { marker: 'fetch(', why: 'רשת' },
  { marker: 'XMLHttpRequest', why: 'רשת' },
  { marker: 'navigator.sendBeacon', why: 'רשת' },
  { marker: 'sendBeacon', why: 'רשת' },
  { marker: 'WebSocket', why: 'רשת' },
  { marker: 'EventSource', why: 'רשת' },
  // אחסון בדפדפן — שמירה אצלה, אחרי שהבטחנו שלא
  { marker: 'localStorage', why: 'אחסון בדפדפן' },
  { marker: 'sessionStorage', why: 'אחסון בדפדפן' },
  { marker: 'indexedDB', why: 'אחסון בדפדפן' },
];

/** ייבוא דינמי עם ביטוי — מה שהופך גרף סטטי לחלקי. */
const DYNAMIC_IMPORT_RE = /\bimport\s*\(\s*[^'")]/;

/**
 * כל ההפרות, על פני כל נקודות הכניסה.
 * מקבלת רשימת כניסות כדי שהמבחן השלילי יוכל להריץ אותה על קובץ פיתיון.
 */
export function findUploadViolations(entries = WATCHED_ENTRIES) {
  const violations = [];
  const scanned = new Set();

  for (const entry of entries) {
    if (!existsSync(join(ROOT, entry))) {
      violations.push({
        file: entry,
        line: 0,
        text: 'נקודת כניסה שלא נמצאה',
        why: 'השער בודק קובץ שאינו קיים — או שהוא נמחק, או שהשם השתנה',
      });
      continue;
    }

    const { files, unresolved } = buildGraph(entry);

    for (const { file, spec } of unresolved) {
      violations.push({ file, line: 0, text: `ייבוא שלא נפתר: ${spec}`, why: 'גרף חלקי' });
    }

    for (const rel of files) {
      if (scanned.has(rel)) continue;
      scanned.add(rel);
      if (/\.(json|css|svg|png)$/.test(rel)) continue;

      for (const { line, n } of codeOf(rel)) {
        for (const { marker, why } of FORBIDDEN_MARKERS) {
          if (line.includes(marker)) {
            violations.push({ file: rel, line: n, text: line.trim(), why: `${why}: ${marker}` });
          }
        }
        if (DYNAMIC_IMPORT_RE.test(line)) {
          violations.push({ file: rel, line: n, text: line.trim(), why: 'ייבוא דינמי' });
        }
      }
    }
  }

  return violations;
}

/** הקבצים שהשער כיסה. מיוצא כדי שהמבחן יוכל לטעון עליהם. */
export function uploadGraphFiles(entries = WATCHED_ENTRIES) {
  const all = new Set();
  for (const entry of entries) {
    if (!existsSync(join(ROOT, entry))) continue;
    for (const rel of buildGraph(entry).files) all.add(rel);
  }
  return Array.from(all).sort();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const violations = findUploadViolations();
  if (violations.length > 0) {
    console.error('\n✖ נמצא נתיב שמוציא או שומר נתונים בהשוואת דוחות הגבייה.\n');
    console.error('  על המסך כתוב: "הקבצים נשארים במחשב שלך. שום דבר מהם לא נשלח לשום מקום ולא נשמר בכלי — כשסוגרים את החלון, זה נעלם."');
    console.error('  כל ממצא כאן הופך את המשפט הזה ללא נכון.\n');
    for (const v of violations) {
      console.error(`  ${v.file}${v.line ? ':' + v.line : ''}  [${v.why}]  ${v.text}`);
    }
    console.error('');
    process.exit(1);
  }
  const files = uploadGraphFiles();
  console.log(`✓ אין נתיב לשליחה או לשמירה בהשוואת הדוחות (${files.length} קבצים בגרף).`);
}
