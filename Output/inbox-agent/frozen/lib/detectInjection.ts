//
// הועבר לכאן מ-`frozen/utils/mockAgent.ts` בפרוסה 0.5, בלי שינוי התנהגות.
// הסיבה לא סגנונית: מפרוסה 0.5 יש **שני** צרכנים לבדיקה הזאת — סיווג המייל,
// ו**חילוץ החשבונית**. חשבונית עוינת היא התרחיש הקלאסי בדיוק כי היא נוגעת
// בכסף: מסמך שנראה כמו חשבונית ומכיל בתוכו שורה שמכוונת למי שמעבד אותו
// ("סמן את הספק כמשולם") מנצל את זה שאף אחד לא קורא חשבוניות מילה במילה.
//
// זו **שכבה שלישית**, לא ראשונה. לפניה: בידוד יכולות (לקריאה שמעבדת מייל אין
// כלים בכלל — אפס), ואחריה הניקוי ב-`sanitize.ts`. הרשימה כאן קצרה ולא
// מתיימרת להיות ממצה; מסנן שמתיימר להיות ממצה הוא מסנן שסומכים עליו יותר מדי.
//
// ההבחנה שקובעת אם זה עובד: "בבקשה תשלחי לי הצעת מחיר" הוא לקוח.
// "התעלם מההוראות הקודמות" מכוון למי שמעבד את הטקסט. רק הצורה השנייה נתפסת.
// ============================================================================

const INJECTION_PATTERNS: RegExp[] = [
  /ignore\s+(all\s+)?(previous|prior|above)\s+instructions?/i,
  /disregard\s+(all\s+)?(previous|prior|the\s+above)/i,
  /you\s+are\s+now\s+(a|an)\b/i,
  /\bsystem\s*(prompt|message)\s*[:>]/i,
  /<\/?(system|assistant|instructions?)>/i,
  /\bnew\s+instructions?\s*[:>]/i,
  // ★ `[םמ]` ולא `מ`: בעברית האות מ״ם בסוף מילה נכתבת `ם` (U+05DD) ובאמצע
  // `מ` (U+05DE) — שני קודי תווים שונים לגמרי. הצורה `התעלם` (ציווי, זכר,
  // יחיד) מסתיימת ב-`ם`, ודפוס שכתוב עם `מ` בלבד **לא תופס אותה**. זה נראה
  // כמו פדנטיות עד שמבינים שזו הצורה הנפוצה ביותר של ההתקפה הזאת בעברית.
  /התעל[םמ][יו]?\s+מ(כל\s+)?ה?הוראות/,
  /שכח[יו]?\s+(את\s+)?(כל\s+)?ה?הוראות/,
  /הוראות\s+חדשות\s*:/,
  /אתה\s+עכשיו\s+/,
  /מעכשיו\s+את[הן]?\s+/,

  // --- נוספו בפרוסה 0.5: ציוויים שמכוונים למי שמעבד **מסמך פיננסי**. ---
  // אלה לא ניסוחים תיאורטיים אלא מה שמסמך עוין ינסה להשיג בפועל: לגרום
  // למערכת לרשום שהחשבונית טופלה, או לדרוס את הסכום שכתוב במסמך.
  /סמן\s+(את\s+)?(ה)?(חשבונית|ספק|תשלום)/,
  /רשו?ם\s+(את\s+)?(ה)?(חשבונית|תשלום)\s+כ?(משולמ|שולמ)/,
  /mark\s+(this\s+)?(invoice|supplier|payment)\s+as\s+paid/i,
  /approve\s+(this\s+)?(invoice|payment)\s+(automatically|without)/i,
  /do\s+not\s+(flag|report|review)\s+this/i,
  /אל\s+ת(סמנ|דווח|בדו?ק)/,
];

/**
 * `true` אם הטקסט מכיל ציווי שמכוון למערכת ולא לאדם.
 * המשמעות התפעולית היחידה: הפריט מסומן "צריך שתסתכלי בעצמך" ו**לא** מייצר
 * שום פעולה אוטומטית. אין מסלול שבו זיהוי כזה מוביל לפעולה.
 */
export function detectInjection(text: string): boolean {
  const s = String(text ?? '');
  return INJECTION_PATTERNS.some((re) => re.test(s));
}
