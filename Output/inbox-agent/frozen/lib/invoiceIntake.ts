// ============================================================================
// invoiceIntake.ts — ★ מי בכלל נכנס. allowlist, לא "כל קובץ מצורף".
//
// ---------------------------------------------------------------------------
// למה שער נפרד, ולמה הוא קשיח
// ---------------------------------------------------------------------------
// `invoiceDetect` עונה על "האם זו חשבונית". השאלה כאן אחרת ומוקדמת יותר:
// **האם מותר לנו בכלל לפתוח ולאחסן את הקובץ הזה.**
//
// הפער בין השתיים הוא מה שהופך פיצ׳ר שימושי למפגע. צינור שמוגדר "כל קובץ
// מצורף שנראה קשור לכסף" יאסוף תוך חודש גם צילום תעודת זהות ששלחה לקוחה,
// גם טופס רפואי שהגיע בטעות, וגם חוזה של צד שלישי. שום שורה בקוד לא תיראה
// שגויה — פשוט כל אחת מהן תרחיב את הצינור קצת.
//
// לכן התנאי הוא **מצטבר**, וכל רכיב בו הוא וטו:
//
//   לא רעש  ∧  מועמד-חשבונית  ∧  PDF  ∧  מתחת לתקרת גודל  ∧  לא רגיש
//
// ---------------------------------------------------------------------------
// ★ הגייט האחרון קשיח: `containsSensitive === true` → לא נכנס. נקודה.
// ---------------------------------------------------------------------------
// **עדיף לפספס חשבונית מאשר לאחסן מסמך רגיש.** אי-סימטריה מכוונת: חשבונית
// שפוספסה עולה חמש דקות של גרירה ידנית מהתיבה. מסמך רפואי שנשמר במאגר שלנו
// מעלה את כל המאגר לרמת אבטחה בינונית, ואי אפשר "לבטל" אחסון בדיעבד.
//
// שים לב ל-`=== true` שאינו סתם סגנון: `undefined` פירושו **שהמודל עוד לא
// רץ**, ולא "לא רגיש". במצב כזה השער מסרב, כי היעדר תשובה אינו תשובה
// שלילית — זו טעות שקטה שקל מאוד לכתוב בטעות כ-`if (!containsSensitive)`.
//
// ---------------------------------------------------------------------------
// PDF בלבד, למרות שהמודל יודע לקרוא תמונות
// ---------------------------------------------------------------------------
// חשבונית סרוקה כ-JPG היא מקרה אמיתי, ובכל זאת התמונות מחוץ לצינור בסבב
// הזה. הסיבה: תמונה בתיבה עסקית היא ברוב המכריע של המקרים **לא** חשבונית
// (חתימות, לוגואים, צילומי מסך, תמונות שלקוחות שולחות), וכל אחת מהן שתיכנס
// היא מסמך של אדם שלא הסכים לכלום. PDF שנשלח בצירוף למייל עם ראיית-חשבונית
// הוא הרבה יותר ממוקד. תמונות יחזרו כשיהיה אישור מפורש פר-מסמך.
// ============================================================================

import type { AttachmentMeta, InvoiceDetection } from '../types/invoice';
import type { Verdict } from '../types/triage';

export type IntakeRefusalCode =
  | 'isNoise'
  | 'notInvoiceCandidate'
  | 'notPdf'
  | 'tooLarge'
  | 'tooSmall'
  | 'sensitive'
  | 'sensitivityUnknown';

export interface IntakeDecision {
  /** ★ האם מותר לפתוח ולאחסן. */
  allowed: boolean;
  refusal?: IntakeRefusalCode;
  /** משפט מוכן להצגה, בגוף ראשון. */
  reasonHe: string;
}

export interface IntakeInput {
  /** פסק הדין של המסנן הדטרמיניסטי על ההודעה. */
  filterVerdict: Verdict;
  detection: InvoiceDetection;
  attachment: AttachmentMeta | null;
  /**
   * ★ פלט המודל על גוף המייל. `undefined` = טרם רץ.
   * שים לב שזה **הכיוון המותר** שבו פלט מודל משפיע: הוא יכול רק **למנוע**
   * קליטה, לעולם לא לאשר אותה. אותו עיקרון כמו בארכוב, בכיוון ההפוך.
   */
  containsSensitive?: boolean;
}

export interface IntakeOptions {
  /** תקרת גודל. 15MB — מעבר לזה זה כבר לא חשבונית אלא תיק מסמכים. */
  maxBytes?: number;
  /** רצפה. קובץ זעיר הוא לוגו או pixel מעקב שנארז כקובץ. */
  minBytes?: number;
}

const DEFAULT_MAX_BYTES = 15 * 1024 * 1024;
const DEFAULT_MIN_BYTES = 2048;

/** ★ ה-allowlist עצמו. רשימה אחת, במקום אחד. */
export const INTAKE_ALLOWED_MIME_TYPES = ['application/pdf'] as const;

function refuse(refusal: IntakeRefusalCode, reasonHe: string): IntakeDecision {
  return { allowed: false, refusal, reasonHe };
}

/**
 * ★ השער. כל וטו עוצר, והסדר הוא מהזול לבדיקה ליקר.
 */
export function invoiceIntakeDecision(
  input: IntakeInput,
  opts: IntakeOptions = {},
): IntakeDecision {
  const maxBytes = opts.maxBytes ?? DEFAULT_MAX_BYTES;
  const minBytes = opts.minBytes ?? DEFAULT_MIN_BYTES;

  // --- 1. רעש. --------------------------------------------------------------
  // פריט שהמסנן קבע עליו רעש לא נפתח בכלל, ולכן גם הקובץ שבו לא נפתח.
  // חשבונית ספק שמגיעה עם כותרות דיוור מגיעה לכאן כ-`unknown` ולא כ-`noise`,
  // כי ראיית החשבונית **מקדמת** אותה במסנן — ראה `triageFilter`, שלב 8.
  if (input.filterVerdict === 'noise') {
    return refuse('isNoise', 'המייל הזה סווג כדיוור, ואני לא פותח קבצים מדיוור');
  }

  // --- 2. מועמד חשבונית. ----------------------------------------------------
  if (input.detection.verdict === 'notInvoice') {
    return refuse('notInvoiceCandidate', 'לא זיהיתי כאן חשבונית, אז לא נגעתי בקובץ');
  }

  const a = input.attachment;
  if (!a) {
    return refuse('notInvoiceCandidate', 'אין כאן קובץ מצורף שאפשר לקרוא ממנו');
  }

  // --- 3. PDF בלבד. ---------------------------------------------------------
  if (!(INTAKE_ALLOWED_MIME_TYPES as readonly string[]).includes(String(a.mimeType).toLowerCase())) {
    return refuse(
      'notPdf',
      'הקובץ הזה אינו PDF. בשלב הזה אני קורא רק קובצי PDF — אם זו חשבונית, כדאי לשמור אותה ידנית',
    );
  }

  // --- 4. גודל. -------------------------------------------------------------
  if (a.sizeBytes > maxBytes) {
    return refuse('tooLarge', 'הקובץ גדול מדי מכדי שיהיה חשבונית, אז לא פתחתי אותו');
  }
  if (a.sizeBytes < minBytes) {
    return refuse('tooSmall', 'הקובץ קטן מכדי להיות מסמך, אז לא פתחתי אותו');
  }

  // --- 5. ★ הגייט הקשיח. ----------------------------------------------------
  if (input.containsSensitive === true) {
    return refuse(
      'sensitive',
      'במייל הזה יש מידע אישי רגיש. לא שמרתי ממנו שום קובץ ולא קראתי ממנו נתונים — אם יש כאן חשבונית, כדאי לשמור אותה בעצמך',
    );
  }
  if (input.containsSensitive === undefined) {
    // היעדר תשובה אינו תשובה שלילית. ראה ההערה בראש הקובץ.
    return refuse(
      'sensitivityUnknown',
      'עוד לא בדקתי אם יש כאן מידע רגיש, ולכן לא נגעתי בקובץ',
    );
  }

  return { allowed: true, reasonHe: 'חשבונית בקובץ PDF, בלי מידע רגיש — קראתי ושמרתי' };
}
