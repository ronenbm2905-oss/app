// ★ דוח שבועי — לראות **אחרי**, לא רק לפני
// ---------------------------------------------------------------------------

export interface ArchivedRecord {
  itemId: string;
  fromDomain: string;
  archivedAt: string;
  reasonHe: string;
}

export interface WeeklyArchiveReport {
  from: string;
  to: string;
  total: number;
  /** לפי דומיין, מהגדול לקטן. דומיין אינו אדם — בטוח להצגה. */
  byDomain: Array<{ domain: string; count: number }>;
  /** משפט מוכן, גוף ראשון. */
  summaryHe: string;
  records: ArchivedRecord[];
}

/**
 * ★ מה ירד מהמסך בשבוע האחרון.
 *
 * חלון ההשהיה נותן לבעלת העסק לראות **לפני**. לא היה שום דבר שנותן לראות
 * **אחרי** — וזה הצד החשוב יותר, כי שם מתגלות טעויות שיטתיות. אצל משתמשת
 * לא-טכנית ההפיכות היא הבקרה היחידה שבאמת פועלת, והיא שווה משהו רק אם היא
 * יודעת מה יש להפוך.
 */
export function weeklyArchiveReport(
  records: readonly ArchivedRecord[],
  opts: { now?: Date | string; days?: number } = {},
): WeeklyArchiveReport {
  const now = asDate(opts.now);
  const days = opts.days ?? 7;
  const from = new Date(now.getTime() - days * 24 * 60 * 60 * 1000);

  const inWindow = records.filter((r) => {
    const d = new Date(r.archivedAt);
    return !isNaN(d.getTime()) && d >= from && d <= now;
  });

  const counts = new Map<string, number>();
  for (const r of inWindow) counts.set(r.fromDomain, (counts.get(r.fromDomain) ?? 0) + 1);

  const byDomain = [...counts.entries()]
    .map(([domain, count]) => ({ domain, count }))
    .sort((a, b) => b.count - a.count || a.domain.localeCompare(b.domain));

  return {
    from: from.toISOString(),
    to: now.toISOString(),
    total: inWindow.length,
    byDomain,
    records: [...inWindow].sort((a, b) => b.archivedAt.localeCompare(a.archivedAt)),
    summaryHe:
      inWindow.length === 0
        ? 'לא הוצאתי מהתיבה שום מייל בשבוע האחרון'
        : `בשבוע האחרון הוצאתי מהתיבה ${inWindow.length} מיילים${
            byDomain[0] ? `, רובם מ-${byDomain[0].domain}` : ''
          }. כולם שמורים ואפשר להחזיר כל אחד בלחיצה`,
  };
}

