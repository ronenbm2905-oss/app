/**
 * דפוסי דומיין של גופים שמייל מהם לא יורד מהתיבה לעולם.
 *
 * הרשימה מכוונת ל**סיומות ולמילים מבניות** ולא לשמות מותג, כי שמות מותג
 * מתיישנים ורשימה שמתיישנת גרועה מרשימה שלא קיימת — היא נותנת ביטחון שווא.
 *
 * הנימוק לכלל עצמו: **מייל מרשות שנקבר הוא מועד שנשרף.** אין דרך לתקן
 * את זה בדיעבד, ואי-הסימטריה בין הנזק (קנס, זכות שהתיישנה) לבין העלות
 * (עוד כמה מיילים בתיבה) גדולה בשני סדרי גודל.
 */
export const INSTITUTIONAL_DOMAIN_PATTERNS: RegExp[] = [
  /(^|\.)gov(\.[a-z]{2})?$/i, // gov.il וכל מקבילה
  /(^|\.)muni(cipal)?\./i,
  /(^|\.)(bank|banking)\./i,
  /(^|\.)[a-z-]*bank[a-z-]*\./i,
  /(^|\.)(mas|misim|taxes|tax)\./i, // רשות המסים ומקבילות
  /(^|\.)btl\./i, // ביטוח לאומי
  /(^|\.)(bituach|insurance)\./i,
  /(^|\.)court(s)?\./i,
];

/** האם הדומיין נראה כמו רשות / בנק / גוף ממשלתי. דטרמיניסטי לחלוטין. */
export function isInstitutionalDomain(domain: string): boolean {
  const d = String(domain ?? '').toLowerCase();
  if (!d) return false;
  return INSTITUTIONAL_DOMAIN_PATTERNS.some((re) => re.test(d));
}

