/**
 * שתי אפשרויות. **אין כאן `delete` ולא יהיה.**
 *
 * זה לא "מחיקה לא ממומשת עדיין" — זה שאין לה שם. מי שירצה להוסיף מחיקה יצטרך
 * לשנות את הטיפוס הזה, כלומר לגעת בקובץ שכתוב בראשו למה אסור. זו ההגנה
 * הזולה ביותר שקיימת מפני "רק נוסיף אופציה".
 */
export type ArchiveAction = 'archive' | 'keep';

/**
 * ★ כלל 10, אכיפה בטיפוס־שכן: אין כאן `markRead`.
 *
 * הקבוע קיים כדי שההכרעה תהיה **כתובה** ולא רק חסרה. מי שיחפש "למה הסוכן
 * לא מסמן כנקרא" ימצא תשובה במקום להניח שזה פשוט לא מומש: אם ארכוב שגוי
 * קרה, הסימון `UNREAD` הוא העקבה היחידה שנשארה כדי למצוא אותו.
 */
export const NEVER_MARK_AS_READ = true as const;

export type ArchiveRule =
  | 'userPinned' // בעלת העסק ביקשה להשאיר
  | 'notNoise' // כלל 1+2: המסנן לא קבע רעש
  | 'ledgerNotTrusted' // ★ הפסק בפנקס לא הגיע מכותרות ולא מהמשתמשת
  | 'orderMessage' // ★★ כלל 11: הודעת הזמנה. חסינות מוחלטת
  | 'invoiceCandidate' // כלל 5: נראה כמו חשבונית
  | 'hasAttachment' // ★ כלל 6: יש קובץ מצורף
  | 'correspondent' // ★ כלל 7: התכתבנו עם הדומיין הזה
  | 'threadActive' // ★ כלל 8: השרשור חסין
  | 'institutional' // ★ כלל 9: רשות / בנק / גוף ממשלתי
  | 'deferralWindow' // כלל 4: טרם הופיע בדוח בוקר
  | 'runCapExceeded' // ★ מפסק הזרם ירה
  | 'eligible'; // עבר את כל הכללים

