// archivePolicy.ts — ★ בטיחות הארכוב. פונקציה טהורה, נבנית **לפני** שיש
// הרשאת כתיבה אמיתית.
//
// ---------------------------------------------------------------------------
// למה זה נכתב עכשיו ולא כשיהיה `gmail.modify`
// ---------------------------------------------------------------------------
// עד היום סיווג שגוי הציג תווית לא נכונה על מסך. **מהרגע שהסוכן מארכב, סיווג
// שגוי מעלים מייל של לקוחה מהתיבה.** זה שינוי בסוג הסיכון ולא בגודלו.
//
// קוד שנכתב יחד עם ההרשאה נכתב תחת לחץ להראות שהוא עובד. קוד שנכתב לפניה
// נבדק על השאלה היחידה שמעניינת: **מה הוא מסרב לעשות.** לכן הקובץ הזה קיים
// בפרוסה שאין בה Google בכלל, ולכל אחד מהכללים יש מבחן ייעודי שמוכיח שהוא
// חוסם — ולא מבחן שמוכיח שארכוב עובד.
//
// ---------------------------------------------------------------------------
// ★ ארבעת הכללים
// ---------------------------------------------------------------------------
//  1. ארכוב **רק** על מה שה**מסנן הדטרמיניסטי** קבע `noise`.
//     פסיקת מודל לעולם לא מארכבת — היא מתייגת בלבד.
//     הסיבה: המסנן ניתן להסבר ולשחזור, המודל לא. אם מייל נעלם, צריך להיות
//     אפשר לומר **איזה כלל** הפיל אותו ולתקן את הכלל.
//
//  2. `signal` ו-`unknown` לא מאורכבים אף פעם, גם לא בהוראת המודל.
//     `unknown` הוא בדיוק המקום שבו המסנן אמר "אני לא יודע" — ופעולה
//     בלתי-הפיכה-למראית-עין על סמך "אני לא יודע" היא הכשל שהכללים נועדו למנוע.
//
//  3. **מארכבים, לא מוחקים.** כל פריט מקבל תווית ייעודית וניתן לשחזור בקליק.
//     זה נאכף בטיפוס: ב-`ArchiveAction` **אין ערך שמשמעותו מחיקה**, ולכן אי
//     אפשר לכתוב קוד שקורא לפונקציה הזאת ומקבל ממנה הוראת מחיקה.
//
//  4. **חלון השהיה.** ארכוב מתבצע רק אחרי שהפריט הופיע בדוח בוקר אחד — כדי
//     שתמיד תהיה הזדמנות לראות לפני שמשהו יורד מהמסך.
//
// ---------------------------------------------------------------------------
// כללים 5–10: מה שסקירת עדי הוסיפה, וכולם לכיוון אחד — עוד סירובים
// ---------------------------------------------------------------------------
//  5. **מועמד חשבונית לא מאורכב אף פעם.**
//     הנימוק אינו "חשבוניות חשובות" אלא מבני: חשבונית ספק מגיעה כמעט תמיד
//     מ-`billing@` או `noreply@`, עם `List-Unsubscribe`, כלומר **המסנן
//     הדטרמיניסטי יסמן אותה `noise`** ותנאי כלל 1 יתקיים. זהו החור היחיד
//     שמצאתי שבו ארבעת הכללים מאשרים ארכוב של משהו שנוגע בכסף.
//
//  6. ★ **מייל עם קובץ מצורף לא מאורכב לעולם.**
//     כאן הנימוק חזק במיוחד, והוא הפוך מהאינטואיציה: `List-Unsubscribe`
//     ו-`Precedence: bulk` **נכתבות בידי השולח**. כלומר הקלט של המסנן נשלט
//     בידי מי שאנחנו מגנים מפניו, ומייל הונאה יכול פשוט להוסיף את הכותרת
//     ולהיארכב. קובץ מצורף הוא סימן ל"מישהו שלח משהו", והוא הרבה יותר יקר
//     לזייף מאשר שורת כותרת.
//
//  7. ★ **דומיין שהתכתבנו איתו חסין לארכוב.** אותה תובנה של `in:sent` מהמסנן,
//     אבל כאן היא **וטו** ולא קדימות: גם אם ההודעה הספציפית נראית כמו דיוור.
//
//  8. ★ **החסינות היא ברמת השרשור, לא ההודעה.** תשובה אוטומטית בתוך שרשור
//     פתוח ("קיבלנו את פנייתך") נושאת `Auto-Submitted` ותיפול לרעש — ואם
//     היא תיארכב, השרשור כולו נעלם מהעין באמצע שיחה חיה.
//
//  9. ★ **רשויות, בנקים וגופים ממשלתיים — `neverAutoNoise`.** מייל מרשות
//     שנקבר הוא מועד שנשרף, ואת זה אי אפשר לתקן בדיעבד.
//
// 10. ★ **אין סימון כנקרא.** הכרעה מפורשת ולא השמטה: `UNREAD` היא העקבה
//     היחידה שנשארת אם משהו השתבש. `ArchiveAction` לא מכיל ערך כזה.
//
// 11. ★★ **הודעת הזמנה לא מאורכבת לעולם.**
//     הנימוק מבני, כמו בכלל 5: הודעת הסליקה מגיעה מכתובת אוטומטית שאף אחד
//     לא השיב לה מעולם, ולכן היא **בדיוק הצורה** שהמסנן הדטרמיניסטי מסמן
//     `noise` — שולח שלא התכתבנו איתו, אין שרשור חי, ואין קובץ מצורף. כלומר
//     בלי הכלל הזה, ארבעת הכללים הראשונים מאשרים ארכוב של **הזמנה ששולמה**.
//
//     ההודעה הזאת אינה רעש בשום מובן: היא **הסיגנל היחיד** שממנו נובעת
//     חבילה. אם היא יורדת מהמסך, לקוחה ששילמה לא מקבלת את מה שקנתה — כשל
//     שמתגלה רק כשהיא מתקשרת לשאול. אין כאן אי-סימטריה לשקול: הצד השני של
//     המאזניים הוא "עוד מייל בתיבה".
//
//     החסינות נשענת על **שולח + נושא** (`isOrderMessage` ב-`orderParse`)
//     ולא על פענוח מוצלח, ובכוונה: גם הודעת הזמנה שלא הצלחנו לקרוא — ואולי
//     דווקא היא — חייבת להישאר מול העיניים.
//
// ---------------------------------------------------------------------------
// ★★ מפסק זרם — הבקרה שאף אחד מהכללים למעלה לא מספק
// ---------------------------------------------------------------------------
// כל עשרת הכללים מטפלים ב**פריט**. אף אחד מהם לא מטפל ב**אירוע**: באג במסנן,
// או פנקס שנפגם, מארכב 100 מיילים בריצה אחת — וכל אחד מהם עובר את כל הכללים
// בנפרד. חלון ההשהיה לא עוזר, כי כולם עברו אותו יחד.
//
// `planArchiveRun` אוכף **תקרה קשיחה לריצה**. מעבר לה הריצה לא מארכבת כלום
// וכותבת הצעה לאישור. ראה שם.
//
// ---------------------------------------------------------------------------
// כל החלטה מחזירה נימוק קריא
// ---------------------------------------------------------------------------
// לא קוד שגיאה ולא דגל בוליאני — משפט בעברית שאפשר להראות על המסך כמו שהוא.
// אם משהו נעלם מהתיבה, התשובה לשאלה "למה" חייבת להיות זמינה **בלי מפתח**.
// ============================================================================

