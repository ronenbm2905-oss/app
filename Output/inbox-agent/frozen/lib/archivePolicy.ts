export interface ArchiveCandidate {
  itemId: string;
  /** לתצוגה בלבד. פריט רעש אינו נושא כותרת, ולכן זה מה שיש. */
  fromDomain: string;

  /**
   * ★ פסק הדין של **המסנן הדטרמיניסטי בלבד**.
   * לא "הפסיקה הסופית", לא "אחרי המודל" — זה שדה אחר, וזה כל העניין.
   */
  filterVerdict: Verdict;
  filterReason: TriageReason;

  /**
   * ★ מה שהמודל חושב.
   *
   * השדה קיים כדי שנוכל **לתעד** אי-הסכמה, ולא כדי להחליט לפיה. הפונקציה
   * לא קוראת אותו בשום ענף שמוביל ל-`archive`. הוא גם לא יכול למנוע ארכוב:
   * "המודל אמר להשאיר" נשמע כמו הגנה, אבל הוא הופך פונקציה דטרמיניסטית
   * לכזו שהתנהגותה תלויה בפלט שאינו ניתן לשחזור, ואז אי אפשר לבדוק אותה.
   */
  agentSuggestsArchive?: boolean;

  /** כלל 5. מגיע מ-`invoiceDetect` — דטרמיניסטי גם הוא. */
  looksLikeInvoice?: boolean;

  /**
   * ★ כלל 6: יש קובץ מצורף.
   * הבדיקה הזאת יקרה לזייף בהשוואה לשורת כותרת, וזה כל ערכה.
   */
  hasAttachment?: boolean;

  /** ★ כלל 7: הדומיין מופיע ב-`in:sent` של 90 יום. וטו מוחלט. */
  isCorrespondentDomain?: boolean;

  /**
   * ★ כלל 8: בשרשור הזה יש הודעה שאינה רעש, או שהמשתמשת השיבה בו.
   * החסינות היא של השיחה, לא של ההודעה הבודדת.
   */
  threadActive?: boolean;

  /** ★ כלל 9: רשות, בנק, ביטוח לאומי, מס הכנסה, גוף ממשלתי. */
  isInstitutional?: boolean;

  /**
   * ★★ כלל 11: ההודעה היא הודעת הזמנה ממערכת הסליקה.
   *
   * מגיע מ-`isOrderMessage` ב-`orderParse.ts` — כלומר משולח ונושא, שניהם
   * דטרמיניסטיים. **לא** מפענוח מוצלח: הזמנה שלא הצלחנו לקרוא היא בדיוק זו
   * שהכי חשוב שתישאר בתיבה.
   */
  isOrderMessage?: boolean;

  /**
   * ★ האם מקור הפסק בפנקס אמין לצורך ארכוב.
   * `false` פירושו שרשומת הפנקס נכתבה ממקור שאינו כותרות ואינו המשתמשת —
   * מצב שלא אמור להתקיים (ראה `senderLedger.ts`), ולכן הוא נחסם ולא מנוצל.
   */
  ledgerVerdictTrusted?: boolean;

  /** בעלת העסק לחצה "להשאיר". גובר על הכול. */
  userPinned?: boolean;

  /** ★ כלל 4: מתי הפריט הופיע לראשונה בדוח בוקר. `null` = טרם הופיע. */
  firstSeenInBriefAt?: string | null;
  /** בכמה דוחות בוקר הוא הופיע. */
  briefAppearances?: number;
}

export interface ArchiveDecision {
  action: ArchiveAction;
  rule: ArchiveRule;
  /** ★ משפט מוכן להצגה. גוף ראשון, בלי מונחים פנימיים. */
  reasonHe: string;
  /** התווית שתוצמד. `null` כשלא מארכבים. */
  label: typeof ARCHIVE_LABEL | null;
  /**
   * ★ תמיד `true` כשמארכבים. השדה קיים כדי שהמסך יוכל להבטיח את זה בכתב
   * מתוך הנתון עצמו, במקום שמישהו יכתוב "ניתן לשחזור" בטקסט קבוע ויקווה.
   */
  restorable: boolean;
  /**
   * מתי הפריט ייעשה כשיר, אם הדבר היחיד שחוסם אותו הוא חלון ההשהיה.
   * `null` בכל מקרה אחר — כולל כשהוא כשיר עכשיו.
   */
  eligibleAt: string | null;
}

export interface ArchivePolicyOptions {
  /** "עכשיו". מוזרק כדי שמבחן לא יהיה תלוי בשעון. */
  now?: Date | string;
  /**
   * כמה שעות חייבות לעבור מההופעה הראשונה בדוח בוקר.
   *
   * 20 ולא 24: הדוח נבנה ב-05:30, ומשתמשת שפותחת אותו ב-08:00 ורואה פריט,
   * אמורה לראות אותו יורד בדוח **של מחר** ולא בעוד יומיים. 24 שעות עגולות
   * היו דוחות את הארכוב במחזור שלם בכל פעם שהיא מאחרת בחצי שעה.
   */
  minHoursAfterFirstBrief?: number;
}

const DEFAULT_MIN_HOURS = 20;

function asDate(v: Date | string | undefined): Date {
  if (v instanceof Date) return v;
  if (typeof v === 'string') {
    const d = new Date(v);
    if (!isNaN(d.getTime())) return d;
  }
  return new Date();
}

function keep(rule: ArchiveRule, reasonHe: string, eligibleAt: string | null = null): ArchiveDecision {
  return { action: 'keep', rule, reasonHe, label: null, restorable: false, eligibleAt };
}

