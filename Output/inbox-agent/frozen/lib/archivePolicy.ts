export interface LabelInput {
  /** ★ הודעת הזמנה. תווית משלה, כדי שיהיה אפשר לחפש הזמנות ב-Gmail עצמו. */
  isOrderMessage?: boolean;
  filterVerdict: Verdict;
  looksLikeInvoice?: boolean;
  actionRequired?: boolean;
  needsHumanReview?: boolean;
}

/**
 * אילו תוויות הסוכן יצמיד. **תמיד** מתוך ה-allowlist, ולעולם לא מתוכן המייל.
 *
 * הפרדה מכוונת מ-`archiveDecision`: תיוג הוא פעולה הפיכה שרואים מיד, ארכוב
 * הוא פעולה שמורידה מייל מהמסך. מותר לתייג על סמך פסיקת מודל
 * (`needsHumanReview`, `actionRequired`) — **ואסור לארכב על סמכה**. שתי
 * פונקציות נפרדות הן מה שמונע מהכלל הזה להישחק בטעות.
 */
export function labelsFor(input: LabelInput): AgentLabel[] {
  const labels: AgentLabel[] = [];
  if (input.isOrderMessage) labels.push(AGENT_LABELS.order);
  if (input.looksLikeInvoice) labels.push(AGENT_LABELS.invoice);
  if (input.needsHumanReview) labels.push(AGENT_LABELS.needsLook);
  else if (input.actionRequired && input.filterVerdict === 'signal') labels.push(AGENT_LABELS.action);
  return labels;
}
