/**
 * מכריעה אם מותר לארכב פריט, ומחזירה נימוק קריא בכל מקרה.
 *
 * הסדר הוא מהחזק לחלש בכוונה: הוראת המשתמשת ראשונה, ואחריה שני הכללים
 * שמסתכלים על **מה הפריט**, ורק לבסוף הכלל שמסתכל על **מתי**. כך הנימוק
 * שמוצג הוא תמיד הסיבה המשמעותית ביותר ולא הראשונה שבמקרה נבדקה.
 */
export function archiveDecision(
  candidate: ArchiveCandidate,
  opts: ArchivePolicyOptions = {},
): ArchiveDecision {
  const now = asDate(opts.now);
  const minHours = opts.minHoursAfterFirstBrief ?? DEFAULT_MIN_HOURS;

  // --- 0. הוראת בעלת העסק. גוברת על הכול. ----------------------------------
  if (candidate.userPinned) {
    return keep('userPinned', 'ביקשת שהמייל הזה יישאר בתיבה, אז אני לא נוגע בו');
  }

  // --- ★★ כלל 11: הודעת הזמנה. הווטו החזק ביותר אחרי הוראת המשתמשת. -------
  // יושב **לפני** כל שאר הווטואים כדי שהנימוק שיוצג יהיה הנכון ביותר, וגם
  // כדי שיהיה בלתי-תלוי בהם: הודעת סליקה לא תיתפס בכלל אחר — אין לה שרשור
  // חי, לא התכתבנו איתה, והדומיין שלה אינו מוסדי.
  if (candidate.isOrderMessage) {
    return keep(
      'orderMessage',
      'זו הודעה על הזמנה ששולמה. הודעת הזמנה לא יורדת מהתיבה אף פעם — מאחוריה יש חבילה שצריך לשלוח',
    );
  }

  // --- ★ כללים 1 + 2: רק `noise` של המסנן הדטרמיניסטי. ----------------------
  // שים לב מה **לא** מופיע בתנאי: `agentSuggestsArchive`. אין ענף בפונקציה
  // הזאת שבו פסיקת מודל מובילה ל-`archive`, וזו הטענה שהמבחנים בודקים.
  if (candidate.filterVerdict !== 'noise') {
    const disagrees = candidate.agentSuggestsArchive === true;
    return keep(
      'notNoise',
      disagrees
        ? 'המייל הזה לא נכנס לקטגוריית הפרסומות לפי הכללים הקבועים. גם אם נראה לי שאפשר לארכב אותו — אני לא מארכב על סמך מה שנראה לי'
        : 'המייל הזה לא נכנס לקטגוריית הפרסומות לפי הכללים הקבועים, אז הוא נשאר',
    );
  }

  // --- ★ הפסק הגיע מהפנקס, אבל הפנקס עצמו לא אמין לצורך ארכוב. -------------
  // מצב שלא אמור להתקיים. בדיוק בגלל זה הוא נבדק: אם הוא כן קורה, הסיבה
  // הסבירה היחידה היא שמישהו כתב לפנקס ממקום שלא היה אמור, וזו הדליפה
  // שכל המבנה נבנה כדי למנוע.
  if (candidate.ledgerVerdictTrusted === false) {
    return keep(
      'ledgerNotTrusted',
      'ההחלטה על השולח הזה לא הגיעה ממקום שאני סומך עליו מספיק כדי להוציא מייל מהתיבה',
    );
  }

  // --- ★ כלל 7: התכתבנו עם הדומיין הזה. וטו. --------------------------------
  if (candidate.isCorrespondentDomain) {
    return keep(
      'correspondent',
      'כבר כתבת לכתובת מהשולח הזה. מייל ממישהו שאת בקשר איתו לא יורד מהתיבה',
    );
  }

  // --- ★ כלל 8: השרשור חי. ---------------------------------------------------
  if (candidate.threadActive) {
    return keep('threadActive', 'זה חלק משיחה פתוחה. אני לא מוציא הודעה מתוך שיחה');
  }

  // --- ★ כלל 9: רשות / בנק / גוף ממשלתי. -------------------------------------
  if (candidate.isInstitutional) {
    return keep(
      'institutional',
      'זה מגיע מרשות או מגוף פיננסי. מייל כזה נשאר בתיבה תמיד — מועד שנשרף אי אפשר להחזיר',
    );
  }

  // --- ★ כלל 5: כל דבר שנראה כמו חשבונית נשאר. ------------------------------
  if (candidate.looksLikeInvoice) {
    return keep(
      'invoiceCandidate',
      'נראה שיש כאן חשבונית. כל מה שנוגע בכסף נשאר בתיבה, גם אם הוא הגיע מכתובת של דיוור',
    );
  }

  // --- ★ כלל 6: יש קובץ מצורף. ----------------------------------------------
  // אחרי כלל 5 ולא לפניו, כדי שהנימוק שיוצג יהיה "חשבונית" כשזו חשבונית —
  // הסבר מדויק יותר עוזר לה יותר מהסבר כללי שנכון גם הוא.
  if (candidate.hasAttachment) {
    return keep(
      'hasAttachment',
      'מצורף כאן קובץ. מישהו טרח לשלוח משהו, וזה לא יורד מהתיבה בלי שתראי',
    );
  }

  // --- ★ כלל 4: חלון ההשהיה. ------------------------------------------------
  const appearances = candidate.briefAppearances ?? 0;
  const firstSeen = candidate.firstSeenInBriefAt ? new Date(candidate.firstSeenInBriefAt) : null;

  if (!firstSeen || isNaN(firstSeen.getTime()) || appearances < 1) {
    return keep(
      'deferralWindow',
      'הגיע היום. אני אף פעם לא מארכב משהו לפני שהראיתי לך אותו בדוח בוקר אחד לפחות',
    );
  }

  const eligibleAt = new Date(firstSeen.getTime() + minHours * 60 * 60 * 1000);
  if (now < eligibleAt) {
    return keep(
      'deferralWindow',
      'הראיתי לך אותו בדוח הבוקר של היום. הוא יארכב רק אחרי הדוח הבא, כדי שתמיד תספיקי לראות',
      eligibleAt.toISOString(),
    );
  }

  // --- כשיר. ----------------------------------------------------------------
  return {
    action: 'archive',
    rule: 'eligible',
    reasonHe: 'דיוור פרסומי שכבר הופיע בדוח בוקר. אני מוציא אותו מהתיבה ומסמן אותו — לא מוחק',
    label: ARCHIVE_LABEL,
    restorable: true,
    eligibleAt: null,
  };
}

// ---------------------------------------------------------------------------
// ★★ מפסק זרם — תקרה קשיחה לריצה
// ---------------------------------------------------------------------------

export interface RunPlan {
  /** מה שיארכב בפועל. ריק לגמרי אם המפסק ירה. */
  toArchive: ArchiveCandidate[];
  /** מה שנשאר, עם ההחלטה שלו. */
  decisions: Map<string, ArchiveDecision>;
  /** ★ האם המפסק ירה. */
  tripped: boolean;
  /** מה שהיה מארכב אלמלא המפסק — ממתין לאישור מפורש. */
  heldForApproval: ArchiveCandidate[];
  /** משפט להצגה. גוף ראשון, בלי מונחים פנימיים. */
  summaryHe: string;
}

export interface RunPlanOptions extends ArchivePolicyOptions {
  /**
   * ★ תקרה מוחלטת לריצה אחת.
   *
   * 40 ולא 200: תיבה של ~120 מיילים ביום, שבה ~90% רעש, מייצרת בסביבות
   * 25–30 מועמדים בריצה יומית. תקרה של 40 עוברת בשקט ביום רגיל ויורה מיד
   * ביום שבו משהו נשבר. תקרה שגבוהה מהתרחיש הרגיל פי כמה היא תקרה שלא תירה
   * אף פעם, כלומר תקרה שלא קיימת.
   */
  maxArchivesPerRun?: number;
  /**
   * תקרה יחסית: לא יותר מהאחוז הזה מכלל הפריטים שנסרקו.
   * שתי תקרות ולא אחת, כי כישלון יכול להיראות משני כיוונים — 40 מתוך 45
   * (אחוז חריג) ו-40 מתוך 4,000 (מספר תקין, ריצה חריגה).
   */
  maxArchiveRatio?: number;
}

const DEFAULT_MAX_PER_RUN = 40;
const DEFAULT_MAX_RATIO = 0.75;

/**
 * ★ מריצה את המדיניות על אצווה, ואוכפת את התקרה.
 *
 * ההתנהגות כשהמפסק יורה היא **לא לארכב כלום** — ולא "לארכב עד התקרה".
 * ארכוב חלקי הוא הגרוע משני העולמות: הוא לא מונע את הנזק, והוא מקשה
 * לאתר אותו כי חלק מהפריטים ירדו וחלק לא. עצירה מלאה משאירה את התיבה
 * בדיוק כפי שהייתה, ומשאירה החלטה אחת ברורה לאדם.
 */
export function planArchiveRun(
  candidates: readonly ArchiveCandidate[],
  opts: RunPlanOptions = {},
): RunPlan {
  const maxPerRun = opts.maxArchivesPerRun ?? DEFAULT_MAX_PER_RUN;
  const maxRatio = opts.maxArchiveRatio ?? DEFAULT_MAX_RATIO;

  const decisions = new Map<string, ArchiveDecision>();
  const eligible: ArchiveCandidate[] = [];

  for (const c of candidates) {
    const d = archiveDecision(c, opts);
    decisions.set(c.itemId, d);
    if (d.action === 'archive') eligible.push(c);
  }

  const overCount = eligible.length > maxPerRun;
  const overRatio = candidates.length > 0 && eligible.length / candidates.length > maxRatio;
  const tripped = overCount || overRatio;

  if (!tripped) {
    return {
      toArchive: eligible,
      decisions,
      tripped: false,
      heldForApproval: [],
      summaryHe:
        eligible.length === 0
          ? 'אין היום מה לארכב'
          // ★ עתיד ולא עבר. הפונקציה בונה **תוכנית**; שום דבר עוד לא קרה,
          // ומשפט בלשון עבר על פעולה שלא בוצעה הוא בדיוק סוג ההודעה
          // שגורמת למישהי לחפש בתיבה מייל שעדיין נמצא בה.
          : `אארכב ${eligible.length} מיילים פרסומיים — כל אחד מהם חוזר בלחיצה אחת`,
    };
  }

  // ★ ירה: כל ההחלטות החיוביות מתהפכות ל"נשאר", עם נימוק שאומר למה.
  const reason = overCount
    ? `ביקשו ממני לארכב ${eligible.length} מיילים בבת אחת, וזה הרבה מהרגיל`
    : `יצא לי שצריך לארכב כמעט את כל התיבה (${eligible.length} מתוך ${candidates.length}), וזה לא נראה נכון`;

  for (const c of eligible) {
    decisions.set(c.itemId, {
      action: 'keep',
      rule: 'runCapExceeded',
      reasonHe: `${reason}. עצרתי ולא נגעתי בכלום — עדיף שתסתכלי`,
      label: null,
      restorable: false,
      eligibleAt: null,
    });
  }

  return {
    toArchive: [],
    decisions,
    tripped: true,
    heldForApproval: eligible,
    summaryHe: `${reason}. **לא ארכבתי כלום** ואני מחכה שתאשרי`,
  };
}

// ---------------------------------------------------------------------------
// ★ החזרה — הבקרה החשובה ביותר, ולכן היא פונקציה ולא הבטחה בטקסט
// ---------------------------------------------------------------------------

/**
 * מחזירה פריט שאורכב.
 *
 * המימוש הוא שורה אחת, וזו הנקודה: **החזרה היא נעיצה.** מרגע שבעלת העסק
 * אמרה "להשאיר", `archiveDecision` מחזיר `keep` בכל ריצה עתידית, כי
 * `userPinned` נבדק ראשון. אין "החזרתי אבל מחר זה יירד שוב" — וזה בדיוק
 * מה שהופך את ההחזרה לאמינה אצל משתמשת לא-טכנית: היא לוחצת פעם אחת.
 *
 * הפונקציה קיימת כדי שיהיה **מבחן** שמוכיח את הטענה, במקום משפט על המסך.
 */
export function restoreArchived(candidate: ArchiveCandidate): ArchiveCandidate {
  return { ...candidate, userPinned: true };
}

