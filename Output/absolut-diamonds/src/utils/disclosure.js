// ההגדרה התפעולית (מפרט העיצוב §2.3). התווית עומדת בדרישה כאשר כל ארבעת
// התנאים מתקיימים:
//   1. גודל התווית ≥ 0.8 × גודל המחיר       (13 / 16 = 0.8125)
//   2. משקל התווית ≥ משקל המחיר             (500 ≥ 500)
//   3. ניגודיות התווית ≥ 7:1 — סף מוחלט     (paper על ink‎.88 מעל הפיקסל
//      הבהיר ביותר האפשרי ≈ 12:1)
//   4. המרחק בין התווית למחיר ≤ 12px, ושתיהן מיושרות לאותו קצה.
//
// הקבועים כאן הם **מקור האמת היחיד**: הרכיבים מרנדרים לפיהם, והם גם נפלטים
// כ-`data-a1d-*` כדי ש-`render:check` יוכל לאמת את ארבעת התנאים על הפלט
// האמיתי במקום על כוונות.
//
// ⚠️ מגבלה מוצהרת: רינדור סטטי אינו מודד פריסה. תנאי 4 נאכף כ**צעד ריווח
// מוצהר** בין בלוק התמונה (שהתווית היא שוליו התחתונים) לבלוק הטקסט שנושא
// את המחיר — ושניהם באותה עמודת סריקה. מדידת פיקסלים אמיתית מחייבת דפדפן.
