export const A1D = {
  labelSizePx: 13, // text-disclosure
  labelWeight: 500, // font-medium
  labelFg: "#F7F7F7", // paper
  labelBg: "#14110F", // ink
  labelBgAlpha: 0.88, // scrimInk
  priceSizePx: 16, // text-title
  priceWeight: 500, // font-medium
  maxGapPx: 12, // צעד ריווח אחד
};

// תווית הגילוי על התמונה.
export const a1dLabelAttrs = () => ({
  "data-a1d": "label",
  "data-a1d-size": A1D.labelSizePx,
  "data-a1d-weight": A1D.labelWeight,
  "data-a1d-fg": A1D.labelFg,
  "data-a1d-bg": A1D.labelBg,
  "data-a1d-alpha": A1D.labelBgAlpha,
});

// המחיר שהתווית נמדדת מולו.
export const a1dPriceAttrs = () => ({
  "data-a1d": "price",
  "data-a1d-size": A1D.priceSizePx,
  "data-a1d-weight": A1D.priceWeight,
});

// האשכול שמכיל את שניהם, עם צעד הריווח המוצהר ביניהם.
export const a1dClusterAttrs = (gapPx = A1D.maxGapPx) => ({
  "data-a1d-cluster": "1",
  "data-a1d-gap": gapPx,
});
