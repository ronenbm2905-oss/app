// זו הנקודה שבה נשבר האקסל: הכתובת שימשה כמפתח, ולכן `תמרי 6` ו-`יעקב תמרי 6`
// היו שני בניינים שונים. כאן לכל ישות `id` שנוצר פעם אחת ולא משתנה לעולם,
// והכתובת היא שדה תצוגה בלבד.
// ============================================================================

let counter = 0;

export function newId(prefix = "id") {
  counter += 1;
  const rand = Math.random().toString(36).slice(2, 8);
  return `${prefix}_${Date.now().toString(36)}${counter.toString(36)}${rand}`;
}

/**
 * נרמול כתובת לצורך **התאמה בלבד** (לא לתצוגה): רווחים כפולים, גרשיים,
 * מקפים ורווח לפני אות סופית. `הר הצופים 7ג` ו-`הר הצופים 7 ג` נותנים מפתח זהה.
 *
 * שים לב: זו פונקציית עזר להצעת מיזוג, לא מיזוג אוטומטי. מיזוג ודאי בלבד —
 * כל ספק נשאר בדוח הסתירות להכרעת רונן.
 */
export function addressKey(raw) {
  return String(raw || "")
    .replace(/["'`״׳]/g, "")
    .replace(/[־–—]/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    // "7 ג" → "7ג": רווח בין ספרה לאות בודדת בסוף אינו הבדל אמיתי
    .replace(/(\d)\s+([א-ת])(?=\s|$)/g, "$1$2")
    .toLowerCase();
}
