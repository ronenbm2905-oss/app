//
// ============================================================================
// הבאג, כדי שלא יחזור:
//
// `useData` החזיק את המצב הנוכחי ב-`dataRef`, ועדכן אותו **ברינדור**
// (`dataRef.current = data` בגוף הרכיב). כל `update(mutator)` שכפל את
// `dataRef.current` כמצב-קדם.
//
// שתי קריאות `update()` באותו handler — למשל `saveVehicle(...)` ואז
// `saveTask(...)` בהוספת רכב — רצות **באותו tick**, לפני שהתרחש רינדור אחד.
// לכן שתיהן שכפלו את **אותו** מצב-קדם, והשנייה דרסה את הראשונה.
// last-write-wins.
//
// התסמין בפועל: המסך הודיע "הרכב נשמר, ופתחנו תזכורת לטסט", וב-localStorage
// היו `vehicles: []` ומשימת טסט **יתומה** שמצביעה ל-vehicleId שלא קיים.
// הדשבורד הציג מצב ריק אחרי שמירה מוצלחת. **איבוד נתונים שקט.**
//
// למה זה נעלם מ-558 אסרשני smoke ומ-215 אסרשני render:check: שניהם בודקים
// **פונקציה טהורה אחת** או **רינדור אחד**. אף אחד מהם לא בודק **רצף כתיבות**.
// ============================================================================
//
// המצב חי כאן, ו**המצביע מתקדם בכתיבה — לא ברינדור**. זו כל האינווריאנטה,
// והיא נבדקת ישירות ב-smoke (סעיף "רצף כתיבות").
//
// למה קובץ נפרד ולא עוד ref בתוך ה-hook: כדי שהסמנטיקה תהיה **בדיקה
// ב-Node, בלי React**. באג שאפשר לבדוק רק בדפדפן הוא באג שיחזור.
// ============================================================================

function clone(o) {
  return JSON.parse(JSON.stringify(o));
}

export function createStore(initial) {
  let current = initial;

  return {
    get: () => current,

    // ⚠️ **הקריאה החשובה ביותר בקובץ.** מקדמת את המצביע סינכרונית ומחזירה
    // { prev, next } — כדי שהקורא יוכל לכתוב דלתא בלי לקרוא שוב.
    apply(mutator) {
      const prev = current;
      const draft = clone(current);
      const result = mutator(draft);
      const next = result || draft;
      current = next; // ← סינכרוני. זה מה שהיה שבור.
      return { prev, next };
    },

    // כתיבה ישירה של מצב שלם (מ-onSnapshot, או איפוס מקומי).
    replace(next) {
      const prev = current;
      current = next;
      return { prev, next };
    },
  };
}
